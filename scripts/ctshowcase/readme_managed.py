"""Is this README someone else's generated output? (issue #71)

A README that a generator owns (a docs build, a templating step, another bot) is never rewritten here: the next
run of that generator would undo our edit and the two would fight forever. Three signals, checked in this order:

  config        `.github/showcase.yml` sets `readme: managed` (`readme: authored` switches detection off)
  front-matter  the README's YAML front matter says it is generated (`generated: true`, `autogenerated: yes`,
                `do_not_edit: true`, `generated_by: <tool>`)
  header        an HTML comment in the first 20 lines reads `Generated by`, `DO NOT EDIT`, `auto-generated` or
                `@generated`

Our own `<!-- showcase:... -->` markers never match. Standard library only.
"""
from __future__ import annotations

import re

from .config import load_yaml_text
from .mdcode import masked

HEADER_LINES = 20
MODES = ("managed", "authored")

_COMMENT = re.compile(r"<!--(.*?)(?:-->|\Z)", re.S)
_HEADER = re.compile(r"generated\s+by\b|do\s+not\s+edit|auto[-_ ]?generated|@generated", re.I)
_FRONT = re.compile(r"\A---[ \t]*\r?\n(.*?)\r?\n(?:---|\.\.\.)[ \t]*(?:\r?\n|\Z)", re.S)
_FALSE = {"", "false", "no", "off", "0", "null", "none", "~"}
_KEYS = {"generated", "autogenerated", "donotedit", "generatedby"}


def config_mode(override: dict | None) -> str | None:
    """`managed` / `authored` from a repo override, None when unset (the older `{header, footer}` mapping is not a mode)."""
    value = (override or {}).get("readme")
    return value if value in MODES else None


def _truthy(value) -> bool:
    if isinstance(value, str):
        return value.strip().lower() not in _FALSE
    return bool(value)


def _front_matter(text: str) -> bool:
    """Decode the front matter with the YAML loader (quoted keys, indentation and trailing comments are YAML's job)."""
    m = _FRONT.match(text)
    if not m:
        return False
    try:
        data = load_yaml_text(m.group(1))
    except Exception:  # not YAML (or PyYAML absent): no claim of generation
        return False
    if not isinstance(data, dict):
        return False
    return any(re.sub(r"[-_ ]", "", str(k)).lower() in _KEYS and _truthy(v) for k, v in data.items())


def _header(text: str) -> bool:
    head = "\n".join(masked(text).splitlines()[:HEADER_LINES])  # code spans (inline and fenced) are documentation
    return any(_HEADER.search(body) for body in _COMMENT.findall(head)
               if not body.strip().startswith("showcase:"))


def source(text: str, override: dict | None = None) -> str | None:
    """`config`, `front-matter` or `header` when the README is generated and must not be rewritten, else None."""
    mode = config_mode(override)
    if mode == "authored":
        return None
    if mode == "managed":
        return "config"
    if _front_matter(text):
        return "front-matter"
    if _header(text):
        return "header"
    return None
