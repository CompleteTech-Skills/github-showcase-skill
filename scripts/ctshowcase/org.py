def snapshot_reads(org: str) -> list[dict]:
    """Read-only commands that build an org snapshot for `org doctor`."""
    return [{"name": "org", "argv": ["gh", "api", f"orgs/{org}"]},
            {"name": "org-graphql", "argv": read_command("org_capture", org=org)},
            {"name": "repos", "argv": ["gh", "repo", "list", org, "--limit", "1000", "--json",
                                       "name,visibility,isFork,isArchived,description,stargazerCount,pushedAt"]},
            {"name": "dot-github", "argv": ["gh", "api", f"repos/{org}/.github/contents/profile"]}]


def avatar_colours(path: str | Path) -> int:
    """O1 colour test: colours covering >= 1% of pixels after quantizing to 8 colours."""
    from PIL import Image
    im = Image.open(path).convert("RGB").resize((128, 128))
    q = im.quantize(colors=8)
    counts = q.getcolors() or []
    total = sum(c for c, _ in counts) or 1
    return sum(1 for c, _ in counts if c / total >= 0.01)


def _snap_org(snap: dict) -> dict:
    o = snap.get("org") or {}
    gql = (snap.get("graphql") or {}).get("data", snap.get("graphql") or {}).get("organization") or {}
    return {"name": o.get("name", gql.get("name")), "description": o.get("description", gql.get("description")),
            "blog": o.get("blog", gql.get("websiteUrl")), "location": o.get("location", gql.get("location")),
            "email": o.get("email", gql.get("email")), "twitter_username": o.get("twitter_username", gql.get("twitterUsername")),
            "is_verified": o.get("is_verified", gql.get("isVerified")), "avatar_url": o.get("avatar_url", gql.get("avatarUrl")),
            "pinned": [n.get("nameWithOwner") for n in ((gql.get("pinnedItems") or {}).get("nodes") or []) if n]
            if gql.get("pinnedItems") is not None else snap.get("pinned_public")}


def doctor(estate: Estate, org: str, snap: dict, *, repo_dir: str | Path | None = None, avatar: str | Path | None = None,
           email_approved: bool | None = None, allow_t3: bool = False) -> dict:
    """O1 avatar, O2 About, O3 profile README, O4 health, O6 pins, O9 banner, O11 verified badge."""
    r = estate.resolver
    login, row, reg = _gate(estate, org, allow_t3=allow_t3, allow_hold=True)
    for m in snap.get("repos") or []:
        if isinstance(m, dict) and m.get("name") and not estate.meta(f"{login}/{m['name']}"):
            estate.add_meta({"owner": login, "repo": m["name"], "visibility": str(m.get("visibility", "")).lower(),
                             "fork": m.get("isFork", m.get("fork")), "archived": m.get("isArchived", m.get("archived")),
                             "description": m.get("description"), "stargazers_count": m.get("stargazerCount", 0),
                             "pushed_at": m.get("pushedAt")})
    so = _snap_org(snap)
    cells: dict[str, str] = {}
    notes: list[str] = []
    # O1 avatar
    if avatar:
        n = avatar_colours(avatar)
        cells["O1"] = "pass" if n > 2 else "fail"
        notes.append(f"O1 {n} colours cover >= 1% (needs > 2)")
    elif so.get("avatar_url") and "identicon" in str(so["avatar_url"]):
        cells["O1"] = "fail"
    else:
        cells["O1"] = "unknown"
    # O2 About
    want, _ = about(estate, org, email_approved=email_approved, allow_t3=allow_t3)
    payload = want.get("payload") or {}
    if so.get("name") is None and so.get("description") is None:
        cells["O2"] = "unknown"
    else:
        diff = [k for k, v in payload.items() if (so.get(k) or "") != v]
        cells["O2"] = "pass" if not diff else "fail"
        notes += [f"O2 {k}: {so.get(k)!r} != {payload[k]!r}" for k in diff]
        if "email" not in payload and not so.get("email"):
            notes.append("O2 email empty (needs-approval:org-email)")
    # O3 profile README
    text = snap.get("profile_readme")
    if text is None and repo_dir and (Path(repo_dir) / "profile" / "README.md").is_file():
        text = (Path(repo_dir) / "profile" / "README.md").read_text(encoding="utf-8")
    data, _ = public_slice(estate, org)
    if text is None:
        cells["O3"] = "unknown"
    else:
        listed = {e["full_name"] for k in ("featured", "forks", "archived") for e in data[k]}
        listed |= {e["full_name"] for s in data["sections"] for e in s["repos"]}
        missing = sorted(f for f in listed if f"github.com/{f}".lower() not in text.lower())
        public_names = {f.split("/", 1)[1].lower() for f in listed}
        leaks = leak_check(text, _private_names(estate, org, data), _notes(reg), public_names, _logins(estate),
                           _public_texts(data))
        cells["O3"] = "fail" if missing or leaks else "pass"
        notes += [f"O3 not listed: {f}" for f in missing] + [f"O3 leak: {h}" for h in leaks]
        if data["public_repo_count"] == 0 and PRIVATE_LINE not in text:
            cells["O3"] = "fail"
            notes.append("O3 the private-org line is missing")
    # O4 health
    h, _ = health(estate, org, repo_dir=repo_dir, allow_t3=allow_t3)
    cells["O4"] = {"pass": "pass", "fail": "fail"}.get(h["result"], "unknown")
    notes += [f"O4 missing: {p}" for p in h.get("add", [])]
    # O6 pins
    want_pins = [(p.get("repo") if isinstance(p, dict) else p) for p in reg.get("pins_public") or []]
    want_pins = [estate.current(f"{login}/{n}") for n in want_pins if estate.is_public(f"{login}/{n}")]
    have = so.get("pinned")
    if not want_pins and data["public_repo_count"] == 0:
        cells["O6"] = "n/a"
    elif have is None:
        cells["O6"] = "unknown"
    else:
        have = [r.slug(x) for x in have]
        ok = [x.lower() for x in have] == [x.lower() for x in want_pins]
        cells["O6"] = "pass" if ok else "fail"
        if not ok:
            notes.append(f"O6 pinned {have} != registry {want_pins}")
    # O9 banner
    files, _src = _dot_github_files(estate, login, repo_dir)
    style = estate.brand.style(r.brand_key(org) or login)
    if files.get("profile/assets/banner.jpg"):
        cells["O9"] = "pass"
    elif style.get("banner") == "keep-existing" or (_tier(row) == "T1" and row.get("flagship") and files.get("profile/assets/intro.svg")):
        cells["O9"] = "n/a"
    elif "profile/assets/banner.jpg" in files:
        cells["O9"] = "fail"
    else:
        cells["O9"] = "unknown"
    # O11 verified badge
    if so.get("is_verified") is True:
        cells["O11"] = "pass"
    elif so.get("is_verified") is False:
        vd = want.get("verified_domain") or {}
        cells["O11"] = "warn" if vd.get("reason") else "fail"
        notes.append(f"O11 not verified: {vd.get('reason') or 'no reason code'}")
    else:
        cells["O11"] = "unknown"
    done = all(v in ("pass", "warn", "n/a") for v in cells.values())
    return {"org": login, "tier": _tier(row), "cells": cells, "done": "yes" if done else "no", "notes": notes,
            "reads": snapshot_reads(login), "checked": date.today().isoformat()}


def as_tsv(r: dict, header: bool = False) -> str:
    cols = ["org", "tier", *[f"{k} {v}" for k, v in ORG_COLUMNS.items()], "done"]
    line = "\t".join([r["org"], r["tier"], *[r["cells"].get(c, "unknown") for c in ORG_COLUMNS], r["done"]])
    return ("\t".join(cols) + "\n" if header else "") + line


def as_md(r: dict, header: bool = False) -> str:
    cols = ["org", "tier", *[f"{k} {v}" for k, v in ORG_COLUMNS.items()], "done"]
    vals = [r["org"], r["tier"], *[r["cells"].get(c, "unknown") for c in ORG_COLUMNS], r["done"]]
    head = ("| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n") if header else ""
    return head + "| " + " | ".join(vals) + " |"


