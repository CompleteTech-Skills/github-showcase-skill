    if repo_dir:
        d = Path(repo_dir)
        files = {p: (d / p).is_file() for p in paths}
        forms = d / ".github" / "ISSUE_TEMPLATE"
        files["_forms"] = forms.is_dir() and any(forms.glob("*.yml"))
