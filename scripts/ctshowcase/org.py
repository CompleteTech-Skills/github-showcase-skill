def label_ops_argv(full: str, ops: list[dict]) -> list[list[str]]:
    out = []
    for op in ops:
        if op["op"] in ("patch", "rename"):
            argv = ["gh", "label", "edit", op["name"]]
            for flag, k in (("--name", "new_name"), ("--color", "color"), ("--description", "description")):
                if op.get(k):
                    argv += [flag, op[k]]
            out.append(argv + ["-R", full])
        elif op["op"] == "create":
            out.append(["gh", "label", "create", op["name"], "--color", op["color"], "--description", op["description"],
                        "-R", full])
    return out


def label_job_id(phase: str, full: str, argv: list[str]) -> str:
    """A writer job id derived from the operation, never its position: `p3.2-OWNER__REPO-label-<create|edit>-<name>
    [-to-<new name>]-<sha256(argv)[:8]>`. Identical plans give identical ids; a re-plan whose operation or content
    differs (the rename released after the estate/polish PR, a patch with other fields) gets a new id, so
    scripts/writer.py never sees one id with two contents."""
    verb, name = argv[2], argv[3]
    new = argv[argv.index("--name") + 1] if "--name" in argv else None
    digest = hashlib.sha256(json.dumps(argv, ensure_ascii=False).encode()).hexdigest()[:8]
    slug = re.sub(r"[^A-Za-z0-9._:@+-]+", "-", f"{name}" + (f"-to-{new}" if new else "")).strip("-.")
    head = f"p{phase}-{full.replace('/', '__')}-label-{verb}-"
    return head + slug[:200 - len(head) - 9] + "-" + digest


def _labels_known(m: dict) -> bool:
    """The capture holds the repository's live labels: a non-empty list (or the scratch format's non-empty repr).
    A missing key, null or an empty list is unknown: `meta --from-gh` records a failed labels GET as [], and GitHub
    seeds every repository with default labels, so planning against [] would create every standard label beside the
    defaults and rename none (`labels --plan` re-reads the live labels instead)."""
    v = m.get("labels")
    return bool(v) and isinstance(v, (list, str)) and v not in ("[]", "")


def labels_plan(estate: Estate, org: str, *, allow_t3: bool = False) -> tuple[dict, int]:
    from . import labels as labelsmod
    login, row, reg = _gate(estate, org, allow_t3=allow_t3)
    tier, fam = _tier(row), row.get("family")
    repos, jobs, logs = [], [], []
    if tier in ("T2-R", "T3") or fam == "romgenie":
        return {"command": "org", "action": "labels", "owner": login, "result": "n/a", "repos": [], "jobs": [],
                "logs": [f"labels:n/a:{tier}"]}, OK
    ai_ascension = estate.resolver.same(login, "AI-Ascension")
    std = labelsmod.standard_labels()
    dep = next((lb for lb in std if lb["name"] == "dependencies"), None)
    names = estate.repos_of(org)
    names.sort(key=lambda n: (estate.visibility(f"{login}/{n}") != "public", n.lower()))  # public first (§6.1)
    defaults = labelsmod.defaults_source(f"{login}/.github", meta=estate.meta(f"{login}/.github"))
    for n in names:
        m = estate.meta(f"{login}/{n}")
        full = estate.current(f"{login}/{n}")  # labels are written where the repository is today
        if m is None or m.get("error") and "labels" not in m:
            repos.append({"repo": full, "result": "unknown", "log": "needs-input:metadata"})
            continue
        if m.get("fork"):
            repos.append({"repo": full, "result": "skip", "log": "fork"})
            continue
        if m.get("archived"):
            repos.append({"repo": full, "result": "skip", "log": "archived"})
            continue
        if m.get("has_issues") is False and n != ".github":
            repos.append({"repo": full, "result": "skip", "log": "has_issues:false"})
            continue
        if not _labels_known(m):  # never plan against [] for labels that were not captured (every create, no rename)
            repos.append({"repo": full, "result": "unknown", "log": "needs-input:labels"})
            logs.append(f"needs-input:labels:{full} (labels --plan reads the live labels)")
            continue
        from .meta import normalize
        existing = normalize(m)["labels"]
        if ai_ascension:  # keeps its own labels.yml; R6 there is only `dependencies` (§6.1, q64)
            cur = next((lb for lb in existing if lb["name"] == "dependencies"), None)
            ops = [] if cur and cur["color"] == dep["color"] else [
                {"op": "patch" if cur else "create", "name": "dependencies", "color": dep["color"],
                 "description": dep["description"], "rule": "§6.1 AI-Ascension dependencies"}]
            lg: list[str] = []
        else:
            # no checkout here: §6.4 rule 0 runs against the captured file lists of the repository and of the org's
            # .github (its default issue forms apply to a repository without forms of its own); unproven renames are held
            ops, lg = labelsmod.plan(existing, None, files=m.get("files"), complete=m.get("files_complete") is True,
                                     defaults=defaults)
        writes = [o for o in ops if o["op"] != "skip"]
        logs += lg
        unchecked = [{"label": o["name"], "new_name": o["new_name"], "check_files": o["check_files"]} for o in ops
                     if o.get("log") == labelsmod.NEEDS_CHECKOUT]
        repos.append({"repo": full, "result": "plan" if writes else "needs-input" if unchecked else "pass", "ops": writes,
                      "logs": lg, **({"needs_checkout": unchecked} if unchecked else {})})
        for argv in label_ops_argv(full, writes):  # ids from the operation, never its position
            jobs.append(job(label_job_id(PHASE["labels"], full, argv), PHASE["labels"], "labels", argv,
                            repo=full, note="§6.3 pass A renames before pass B creates; never --force, never a delete."))
    if not ai_ascension and fam != "romgenie" and tier in ("T1", "T2"):
        labels_txt = "; ".join(f"{lb['name']} ({lb['color']})" for lb in std)
        jobs.append(browser_job(
            f"p{PHASE['defaults']}-{login}-repository-defaults", PHASE["defaults"],
            f"https://github.com/organizations/{login}/settings/repository-defaults",
            [f"Open https://github.com/organizations/{login}/settings/repository-defaults.",
             "Under 'Repository default branch', set the name to main and click 'Update'.",
             f"Under 'Repository labels', make the list exactly the {len(std)} §6.2 labels with these colours and "
             f"descriptions from labels.yml: {labels_txt}.",
             f"Screenshot the page into state/screens/{login}/repository-defaults.png."],
            org=login, ui_action="org-repository-defaults", note="RT-16: org repository defaults (new repos only)."))
    unknown = [x["repo"] for x in repos if x.get("log") == "needs-input:metadata"]
    if unknown and len(unknown) == len(repos):  # no --meta-dir (or the wrong one): nothing was checked, so plan nothing
        return {"command": "org", "action": "labels", "owner": login, "result": "needs-input", "repos": repos, "jobs": [],
                "error": f"none of the {len(repos)} repositories of {login} has metadata: pass --meta-dir",
                "logs": sorted(set(logs) | {"needs-input:metadata"})}, NEEDS_INPUT
    if unknown:
        logs.append(f"needs-input:metadata:{len(unknown)}")
    # a rename rule 0 could not check, or labels that were not captured, is never a pass
    held = any(x.get("needs_checkout") or x.get("log") == "needs-input:labels" for x in repos)
    return {"command": "org", "action": "labels", "owner": login, "result": "plan" if jobs else "needs-input" if held else "pass",
            "repos": repos, "jobs": jobs, "logs": sorted(set(logs))}, OK


