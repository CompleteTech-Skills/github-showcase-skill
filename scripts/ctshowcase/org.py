def _star_entry(estate: Estate, org: str, reg: dict) -> dict | None:
    r = estate.resolver
    for e in (r.registry.get("profile") or {}).get("star_lists") or []:
        if isinstance(e, dict) and e.get("source_org") and r.same(e["source_org"], org):
            return e  # the reviewed profile entry wins (registry README rule 5)
    sl = reg.get("star_list") or {}
    return sl if sl.get("name") else None


def _star_held(estate: Estate, org: str) -> str | None:
    st = estate.resolver.owner_status(org)
    if st in ("t3", "hold", "excluded"):
        return st
    if estate.resolver.family_hold(org):
        return "hold"
    return None


def _family_group(estate: Estate, org: str, fam: str | None) -> list[str]:
    """Sibling orgs: the reviewed directory group (registry profile.org_directory) holding this org, else the brand
    family. The Jev group spans two brand families, so the directory is the better source."""
    r = estate.resolver
    for g in (r.registry.get("profile") or {}).get("org_directory") or []:
        orgs = [o for o in (g or {}).get("orgs") or [] if isinstance(o, str)]
        if any(r.same(o, org) for o in orgs):
            return orgs
    return [k for k, v in ((estate.brand.raw.get("orgs") if estate.brand else None) or {}).items()
            if (v or {}).get("family") == fam and k in (r.registry.get("orgs") or {})]


def public_favorites(estate: Estate, reg: dict, *, allow_t3: bool = False) -> tuple[list[str], list[str]]:
    """The registry favorites that may be named in public (the profile's Favorites and the org's public star List):
    someone else's project with no captured metadata as written; an estate favorite, or any favorite whose metadata
    was captured, only when it is in the public slice (public, not HOLD or excluded, not an exposure repo), under
    today's slug. A private, HOLD, excluded-owner or exposure one is dropped and logged without its name (q24); an
    estate one with unknown visibility fails closed and is logged needs-input:favorite-visibility until it is captured.
    A T3 org's repository waits for co-owner sign-off (decision 12, `--allow-t3`) and is logged t3-signoff:OWNER/REPO."""
    r = estate.resolver
    favorites, logs = [], []
    for f in reg.get("favorites") or []:
        full = f.get("full_name") if isinstance(f, dict) else None
        if not full:
            continue
        owner = full.split("/")[0]
        if "/" not in full or not estate.owns(owner) and estate.meta(r.slug(full)) is None:
            favorites.append(full)  # someone else's project: public on GitHub, outside the estate's slice
        elif _t3_held(estate, full, allow_t3):
            logs.append(f"t3-signoff:{full}")  # T3 work waits for co-owner sign-off (decision 12)
        elif estate.is_public(r.slug(full)):
            favorites.append(estate.current(r.slug(full)))
        elif estate.visibility(r.slug(full)) == "unknown" and r.owner_status(owner) != "excluded":
            logs.append(f"needs-input:favorite-visibility:{full}")  # fails closed until its metadata is captured
        else:
            logs.append("favorite-dropped:private-or-unknown")  # private, HOLD or exposure: never named (q24)
    return favorites, logs


def _t3_held(estate: Estate, full: str, allow_t3: bool) -> bool:
    """A repository of a T3 org (any of its logins) before co-owner sign-off: never named on a public profile."""
    return not allow_t3 and "/" in (full or "") and estate.resolver.owner_status(full.split("/")[0]) == "t3"


def public_slice(estate: Estate, org: str, lists_capture: dict | None = None, *,
                 allow_t3: bool = False) -> tuple[dict, list[str]]:
    """The sanitized data the profile is rendered from (and committed as profile/data.json): no private repo, no
    members-only pin, no why/notes text."""
    r = estate.resolver
    login = r.canonical(org)
    row = r.brand_org(org)
    reg = r.registry_org(org)
    prof = reg.get("profile") or {}
    logs: list[str] = []
    desc = prof.get("description") or row.get("description") or ""
    if row.get("description") and prof.get("description") and row["description"] != prof["description"]:
        logs.append("identity-drift:description")
    if not desc:
        logs.append("needs-input:org-description")
    names = estate.repos_of(org)
    public = [n for n in names if n != ".github" and estate.is_public(f"{login}/{n}")]
    for n in names:
        if n != ".github" and estate.visibility(f"{login}/{n}") == "unknown":
            moving = estate.pending_move(f"{login}/{n}")
            logs.append(f"pending-move:{n}:{moving}" if moving else f"needs-input:visibility:{n}")
        if (hit := estate.alias(f"{login}/{n}")) and n in public:
            logs.append(f"repo-alias:{n}->{hit[0]}:{hit[1]}")  # linked under today's slug; regenerate after it runs
    if any(estate.meta(f"{login}/{n}") and not estate.meta(f"{login}/{n}").get("last_substantive_commit")
           for n in public):
        logs.append("recency:pushed_at")

    def m(n):
        return estate.meta(f"{login}/{n}") or {}

    active = [n for n in public if not m(n).get("fork") and not m(n).get("archived")]
    forks = flagship_order([n for n in public if m(n).get("fork")], login, estate)
    archived = flagship_order([n for n in public if m(n).get("archived") and not m(n).get("fork")], login, estate)

    def entry(n, owner=login):
        mm = estate.meta(f"{owner}/{n}") or {}
        full = mm.get("_full") or f"{owner}/{n}"  # today's slug: a pending rename's new URL would 404 until it runs
        return {"repo": full.split("/", 1)[1], "full_name": full, "url": f"https://github.com/{full}",
                "description": mm.get("description") or "", "license": _license(mm)}

    featured = []
    for p in (reg.get("pins_public") or [])[:MAX_PINS]:
        n = p.get("repo") if isinstance(p, dict) else p
        if n in active:
            featured.append(entry(n))
        elif n in public:
            logs.append(f"featured-not-active:{n}")
        else:
            logs.append(f"featured-dropped:{n}")  # not public (or unknown): never named on the profile
    sections, listed = [], set()
    for sec in reg.get("sections") or []:
        title = (sec or {}).get("title") or "Projects"
        if title.strip().lower() in ("forks", "archived"):
            continue
        keep = [n for n in sec.get("repos") or [] if n in active and n not in listed]
        if keep:
            sections.append({"title": title, "repos": [entry(n) for n in flagship_order(keep, login, estate)]})
            listed.update(keep)
    for n in flagship_order([n for n in active if n not in listed], login, estate):
        logs.append(f"needs-input:section:{n}")  # O3 wants every public repo; the registry decides where it goes
    also, seen = [], set()
    incoming = [x.get("repo") for x in reg.get("also_in_incoming") or [] if isinstance(x, dict)]
    for other_key, other in (r.registry.get("orgs") or {}).items():
        for x in other.get("also_in_outgoing") or []:
            if any(r.same(t, org) for t in x.get("also_in") or []):
                incoming.append(f"{other_key}/{x.get('repo')}")
    for full in incoming:
        if not full or "/" not in full:
            continue
        full = r.slug(full)
        if full.lower() in seen:
            continue
        seen.add(full.lower())
        if _t3_held(estate, full, allow_t3):
            logs.append(f"t3-signoff:{full}")  # a T3 org's cross-listing waits for co-owner sign-off (decision 12)
        elif estate.is_public(full):
            o, n = full.split("/", 1)
            also.append(entry(n, o))
        else:
            logs.append("also-in-dropped:private-or-unknown")  # q24: a private cross-listing is never named
    fam = row.get("family")
    siblings = []
    for key in _family_group(estate, org, fam):
        if r.same(key, org) or r.is_placeholder(key):
            continue
        try:
            srow = r.brand_org(key)
        except NeedsInput:
            continue
        if _tier(srow) in ("T1", "T2") and not _star_held(estate, key):
            siblings.append({"login": r.canonical(key), "name": srow.get("display_name") or key})
    siblings.sort(key=lambda s: s["name"].lower())
    favorites, fav_logs = public_favorites(estate, reg, allow_t3=allow_t3)
    logs += fav_logs
    star = None
    entry_sl = _star_entry(estate, org, reg)
    if entry_sl and not _star_held(estate, org):
        slug = list_slug(entry_sl["name"])
        for node in _lists_nodes(lists_capture):
            if node.get("name", "").lower() == entry_sl["name"].lower() and node.get("slug"):
                slug = node["slug"]
        star = {"name": entry_sl["name"], "url": f"https://github.com/stars/{USER_LOGIN}/lists/{slug}"}
    data = {"std": STANDARD, "org": login, "display_name": row.get("display_name") or login, "tier": _tier(row),
            "family": fam, "mission": first_sentence(desc), "blog": prof.get("blog") or "",
            "featured": featured, "sections": sections, "forks": [entry(n) for n in forks],
            "archived": [entry(n) for n in archived], "also_from": also, "siblings": siblings,
            "favorites": favorites, "star_list": star, "public_repo_count": len(public)}
    return data, logs


def _private_names(estate: Estate, org: str, data: dict) -> set[str]:
    """Names that must never appear in public files: non-public repos of this org, every members-only pin, private
    cross-listings and estate favorites, and every estate repository of any org whose metadata says it is not public."""
    r = estate.resolver
    login = r.canonical(org)
    reg = r.registry_org(org)
    shown = {e["full_name"].lower() for k in ("featured", "forks", "archived", "also_from") for e in data[k]}
    shown |= {e["full_name"].lower() for s in data["sections"] for e in s["repos"]}
    out = set()
    for n in estate.repos_of(org):
        if n == ".github":
            continue  # MUST be public (§8.1); the footer links its health files
        if estate.current(f"{login}/{n}").lower() not in shown and not estate.is_public(f"{login}/{n}"):
            out.add(f"{login}/{n}")
    for p in reg.get("pins_members") or []:
        n = p.get("repo") if isinstance(p, dict) else p
        if n and n != ".github" and not estate.is_public(f"{login}/{n}"):
            out.add(f"{login}/{n}")
    for x in reg.get("also_in_incoming") or []:
        full = r.slug(x.get("repo") or "") if isinstance(x, dict) else ""
        if "/" in full and not estate.is_public(full):
            out.add(full)
    for f in reg.get("favorites") or []:  # a favorite left out of the slice (private, HOLD, excluded, exposure, unknown)
        full = r.slug(f.get("full_name") or "") if isinstance(f, dict) else ""
        if "/" in full and (estate.owns(full.split("/")[0]) or estate.meta(full) is not None) and not estate.is_public(full):
            out.add(full)
    for m in estate.metas.values():  # every other repository captured as not public, in any org, whoever the owner
        full = m["_full"]
        if m["_repo"] != ".github" and full.lower() not in shown and estate.visibility(full) != "unknown" \
                and not estate.is_public(full):
            out.add(full)
    out |= {estate.current(f) for f in out}  # a pending rename's private repository is guarded under both slugs
    # CQ-03: a public file may still link a private repository under a former login of its org (an approved rename,
    # former_slugs), which GitHub redirects; guard every login the resolver knows for the owner
    return {f"{a}/{f.split('/', 1)[1]}" for f in out for a in r.aliases(f.split("/", 1)[0])} | out


def _public_texts(data: dict) -> list[str]:
    ents = [e for k in ("featured", "forks", "archived", "also_from") for e in data[k]]
    ents += [e for s in data["sections"] for e in s["repos"]]
    descs = [e["description"] for e in ents if e.get("description")]
    return descs + [json.dumps(d, ensure_ascii=False)[1:-1] for d in descs]


def _logins(estate: Estate) -> set[str]:
    r = estate.resolver
    keys = set((r.registry.get("orgs") or {})) | set(((estate.brand.raw.get("orgs") if estate.brand else None) or {}))
    return {a.lower() for k in keys for a in r.aliases(k)} | {USER_LOGIN.lower()}


def _notes(reg: dict) -> list[str]:
    """Internal why/notes/evidence text from the registry row (must never reach a public file)."""
    out = []

    def walk(v, key=""):
        if isinstance(v, dict):
            for k, x in v.items():
                walk(x, k)
        elif isinstance(v, list):
            for x in v:
                walk(x, key)
        elif isinstance(v, str) and key in ("why", "notes", "evidence", "open_questions", "purpose"):
            out.extend(s.strip() for s in re.split(r"(?<=[.!?])\s+", v) if len(s.strip()) >= 40)
    walk(reg)
    return out


PUBLIC_PROFILE_KEYS = ("name", "bio", "who_what", "intro", "socials", "blog", "company", "location", "email", "pins",
                       "more_projects", "org_directory", "star_lists")


def _all_text(v) -> list[str]:
    """Every sentence of 40 characters or more anywhere in a value (internal blocks with no public field)."""
    out = []
    if isinstance(v, dict):
        for x in v.values():
            out += _all_text(x)
    elif isinstance(v, list):
        for x in v:
            out += _all_text(x)
    elif isinstance(v, str):
        out.extend(s.strip() for s in re.split(r"(?<=[.!?])\s+", v) if len(s.strip()) >= 40)
    return out


def registry_notes(registry: dict) -> list[str]:
    """Internal text outside the org rows that must never reach a public file (OPS-03): the registry's top-level
    `notes` and `judge_changes`, and in the personal `profile` block every internal key (`notes`, `romgenie`, any
    other non-public key, and the why/notes/evidence of its pins and lists). Public profile fields (bio, intro,
    who_what, socials, ...) are not notes."""
    out = _all_text(registry.get("notes")) + _all_text(registry.get("judge_changes"))
    prof = registry.get("profile") or {}
    if isinstance(prof, dict):
        out += _all_text({k: v for k, v in prof.items() if k not in PUBLIC_PROFILE_KEYS})
        out += _notes({k: prof.get(k) for k in PUBLIC_PROFILE_KEYS if prof.get(k) is not None})
    return list(dict.fromkeys(out))


def leak_check(text: str, private: set[str], notes: list[str], public_names: set[str], logins: set[str] = frozenset(),
               public_texts: list[str] | tuple = ()) -> list[str]:
    """`lint public-leak` for one file: private slugs, distinctive private names, internal note sentences.

    Owner positions (`github.com/<login>`), org logins and verbatim public descriptions (already public on GitHub)
    are masked before the bare-name scan, so a product or domain name a public repo states is not a hit."""
    hits = []
    low = text.lower()
    bare = re.sub(r"(github\.com|githubusercontent\.com)/[a-z0-9-]+", r"\1/_", low)
    for s in sorted({x.lower() for x in public_texts if x}, key=len, reverse=True):
        bare = bare.replace(s, " ")
    for full in sorted(private):
        o, n = full.split("/", 1)
        if re.search(rf"{re.escape(f'{o}/{n}'.lower())}(?![a-z0-9_-]|\.[a-z0-9])", low):
            hits.append(f"private-slug:{full}")
            continue
        distinctive = len(n) >= 6 and re.search(r"[-_.0-9]", n) and n.lower() not in public_names | logins
        if distinctive and re.search(rf"(?<![a-z0-9._-]){re.escape(n.lower())}(?![a-z0-9_-]|\.[a-z0-9])", bare):
            hits.append(f"private-name:{full}")
    for s in notes:
        if s.lower() in low:
            hits.append(f"internal-note:{s[:48]}")
    return hits


def estate_leak_scope(estate: Estate, orgs: list[str] | None = None) -> tuple[dict, list[str]]:
    """What `lint public-leak FILE...` checks any public file against: the private names, internal notes, public names
    and public texts of every registry org (or just `orgs`), computed once. An org whose slice cannot be built (no
    registry row, a placeholder) is skipped and logged; unknown visibility fails closed (the repository counts as private)."""
    r = estate.resolver
    priv: set[str] = set()
    notes: list[str] = []
    public_names: set[str] = set()
    texts: list[str] = []
    logs: list[str] = []
    for org in orgs or list(r.registry.get("orgs") or {}):
        try:
            reg = r.registry_org(org)
            data, _ = public_slice(estate, org)
        except ShowcaseError as exc:
            logs.append(f"leak-scope-skipped:{org}:{exc.log}")
            continue
        priv |= _private_names(estate, org, data)
        notes += _notes(reg)
        listed = [e for k in ("featured", "forks", "archived", "also_from") for e in data[k]]
        listed += [e for s in data["sections"] for e in s["repos"]]
        public_names |= {e["repo"].lower() for e in listed}
        public_names |= {f.split("/", 1)[1].lower() for f in data["favorites"] if "/" in f}
        public_names |= {_host(data["blog"]).removeprefix("www."), _host(data["blog"])} - {""}
        texts += _public_texts(data)
    notes += registry_notes(r.registry)  # top-level notes, judge_changes and the profile's internal keys (OPS-03)
    return {"private": priv, "notes": list(dict.fromkeys(notes)), "public_names": public_names,
            "logins": _logins(estate), "public_texts": texts}, logs


def public_leaks(text: str, scope: dict) -> list[str]:
    """`lint public-leak` for one file against an estate_leak_scope()."""
    return sorted(set(leak_check(text, scope["private"], scope["notes"], scope["public_names"], scope["logins"],
                                 scope["public_texts"])))


