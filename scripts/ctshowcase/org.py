def profile_readme(estate: Estate, org: str, data: dict, *, banner: str | None = None, email: str | None = None,
                   no_card: dict | None = None) -> tuple[str, list[dict]]:
    """Render profile/README.md (kit section order) and the badge specs it references. `banner=""` leaves the hero out
    (a kept banner that could not be found); `no_card` lists repositories shown as a Markdown line instead of a card."""
    r = estate.resolver
    login = r.canonical(org)
    row = r.brand_org(org)
    name = data["display_name"]
    flagship = _tier(row) == "T1" and row.get("flagship")
    if banner is None:
        banner = "assets/intro.svg" if flagship else "assets/banner.jpg"
    out = [f"{GENERATED_MARK} from the public slice ({STANDARD}). Edit the registry, then regenerate; do not edit by "
           "hand. -->", ""]
