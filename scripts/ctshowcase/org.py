def _user_cards(entries: list[dict], no_card: dict) -> list[str]:
    carded = [e for e in entries if e["full_name"] not in no_card]
    out = []
    for i in range(0, len(carded), 2):
        row = []
        for e in carded[i:i + 2]:
            alt = f"{e['repo']}: {e['description']}" if e["description"] else e["repo"]
            row.append(f'  <a href="{e["url"]}"><img src="assets/cards/{e["full_name"].replace("/", "__")}.svg" '
                       f'width="400" alt="{_attr(alt)}"></a>')
        out += ["<p>", *row, "</p>", ""]
    rest = [e for e in entries if e["full_name"] in no_card]
    if rest:
        out += [f"- [`{e['repo']}`]({e['url']})" + (f": {_md_text(e['description'])}" if e["description"] else "")
                for e in rest] + [""]
    return out


def _render_tiles(estate: Estate, orgs: list[dict]) -> tuple[dict, set]:
    from . import svglint
    from . import tile as tilemod
    from .typeset import Fonts
    fonts, svgs, failed = None, {}, set()
    for o in orgs:
        try:
            fonts = fonts or Fonts(estate.brand)
            svg, _ = tilemod.render(estate.brand, fonts, o["brand_key"], None, None)
        except ShowcaseError:
            failed.add(o["login"])
            continue
        if svglint.lint_bytes("tile", svg.encode(), o["login"])["result"] != "PASS":
            failed.add(o["login"])
            continue
        svgs[o["login"]] = svg
    return svgs, failed


