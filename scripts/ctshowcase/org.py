def _email(estate: Estate, login: str, reg: dict, approved: bool | None) -> tuple[str | None, str]:
    want = (reg.get("profile") or {}).get("email") or STEWARD_EMAIL
    if approved is None:
        r = estate.resolver
        ans = (r.approvals.get("answers") or {}).get("q26") or {}
        approved = r.approved("org-email", login) or (isinstance(ans, dict) and ans.get("email") in ("set", "yes", True))
    return (want, "approved") if approved else (None, "needs-approval:org-email")


def verified_domain(blog: str, email: str | None, domains: list[str], *, hold=False, in_enterprise=None) -> dict:
    """§14.3: the badge needs both the website and the email on a verified domain (enterprise-owned orgs)."""
    host = _host(blog)
    edom = (email or "").split("@")[-1].lower() if email else ""
    doms = {d.lower() for d in domains}
    if hold:
        reason = "hold"
    elif in_enterprise is False:
        reason = "outside-enterprise"
    elif host not in doms:
        reason = "blog-other-domain"
    elif not edom:
        reason = "email-blank"
    elif edom not in doms:
        reason = "email-mismatch"
    else:
        reason = None
    return {"blog_domain": host or None, "email_domain": edom or None, "verified_domains": sorted(doms),
            "badge_eligible": reason is None, "reason": reason}


def about(estate: Estate, org: str, *, email_approved: bool | None = None, allow_t3: bool = False,
          in_enterprise: bool | None = None) -> tuple[dict, int]:
    r = estate.resolver
    if r.is_placeholder(org):
        login = r.canonical(org)
        return {"command": "org", "action": "about", "owner": login, "result": "user-step", "successor": r.successor(org),
                "logs": ["placeholder-org"], "note": "Placeholder orgs are user checklist items (STANDARD §2.3, ART-01)."}, OK
    login, row, reg = _gate(estate, org, allow_t3=allow_t3, allow_hold=True)
    prof = reg.get("profile") or {}
    logs: list[str] = []
    hold = r.family_hold(org) or r.owner_status(org) == "hold"
    payload: dict = {}
    for k in ("name", "description", "blog", "location"):
        v = prof.get(k)
        if v not in UNSET and not (hold and k in ("description", "location")):
            payload[k] = v
        elif k == "blog" and v in UNSET:
            logs.append("needs-input:blog")
    if prof.get("description") and row.get("description") and prof["description"] != row["description"]:
        logs.append("identity-drift:description")
    if _tier(row) == "T1":
        payload["twitter_username"] = X_HANDLE
    email, why = _email(estate, login, reg, email_approved)
    if email and not hold:
        payload["email"] = email
    else:
        logs.append(why if not hold else "hold")
    fails = []
    if len(payload.get("description", "")) > ORG_DESC_MAX:
        fails.append(f"description is {len(payload['description'])} characters (max {ORG_DESC_MAX})")
    if re.search(r"[\U0001F000-\U0001FAFF]", payload.get("description", "")):
        fails.append("description has an emoji")
    from .enterprise import desired
    try:
        domains = list((desired() or {}).get("domains") or [])
    except Exception:  # an unreadable enterprise.yaml must not block the About plan
        domains = []
    vd = verified_domain(payload.get("blog") or prof.get("blog") or "", payload.get("email"), domains or
                         ["complete.tech", "www.complete.tech"], hold=hold, in_enterprise=in_enterprise)
    if vd["reason"]:
        logs.append(vd["reason"])
    argv = ["gh", "api", "-X", "PATCH", f"orgs/{login}"]
    for k, v in payload.items():
        argv += ["-f", f"{k}={v}"]
    jobs = [] if fails or not payload else [job(
        f"p{PHASE['about']}-{login}-about", PHASE["about"], "org-about", argv, org=login,
        note="STANDARD §2.3 About fields from registry orgs.<org>.profile; email only once approved (q26).",
        read=["gh", "api", f"orgs/{login}"], want=payload)]
    res = {"command": "org", "action": "about", "owner": login, "result": "fail" if fails else "ok", "payload": payload,
           "gh": shlex.join(argv) if jobs else None, "jobs": jobs, "verified_domain": vd, "errors": fails,
           "logs": sorted(set(logs))}
    return res, CHECK_FAILED if fails else OK


