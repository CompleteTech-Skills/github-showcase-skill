def first_sentence(text: str) -> str:
    return re.split(r"(?<=[.!?])\s+", (text or "").strip())[0] if text else ""


def _last(m: dict | None) -> str:
    """CQ-16: last_substantive_commit, else pushed_at (logged by the caller)."""
    if not m:
        return ""
    return str(m.get("last_substantive_commit") or m.get("pushed_at") or "")


def flagship_order(names: list[str], org: str, estate: Estate) -> list[str]:
    """STANDARD §1.4: stars desc, then last_substantive_commit desc, then name asc."""
    out = sorted(names, key=lambda n: n.lower())
    out.sort(key=lambda n: _last(estate.meta(f"{org}/{n}")), reverse=True)
    out.sort(key=lambda n: -int((estate.meta(f"{org}/{n}") or {}).get("stargazers_count") or 0))
    return out


def _license(m: dict) -> str:
    lic = m.get("license")
    if isinstance(lic, dict):
        lic = lic.get("spdx_id") or lic.get("key")
    return "—" if not lic or str(lic).upper() in ("NOASSERTION", "OTHER") else str(lic)


def _cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip() or "—"


def _host(url: str) -> str:
    m = re.match(r"^https?://([^/]+)", url or "")
    return m.group(1).lower() if m else ""


def list_slug(name: str) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", (name or "").lower())).strip("-")


def job(jid: str, phase: str, kind: str, argv: list[str] | None = None, *, org: str | None = None,
        repo: str | None = None, note: str = "", approval_id: str | None = None, **extra) -> dict:
    j: dict = {"id": jid, "phase": phase, "kind": kind}
    if repo:
        j["repo"] = repo
    else:
        j["org"] = org
    if approval_id:
        j["approval_id"] = approval_id
    if argv is not None:
        j["argv"] = argv
    j["note"] = note
    j.update(extra)
    if kind == "labels" and repo:
        j.setdefault("group", f"labels:{repo}")
    return j


def browser_job(jid: str, phase: str, url: str, steps: list[str], *, org: str, ui_action: str, note: str = "",
                **extra) -> dict:
    return job(jid, phase, "browser", None, org=org, note=note, ui_action=ui_action, url=url, steps=steps, **extra)


