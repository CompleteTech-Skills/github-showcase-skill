def _pin_slug(estate: Estate, login: str, name: str, dep: str) -> tuple[str, str | None, str | None, str | None]:
    """(repo name to pin now, gate text, log, slug before the action) for a pin with a `depends_on` action id or gate.

    Approved: pin the registry's final slug once the action has run. Not approved: a same-org rename pins today's
    slug; a transfer into the org is blocked (the repository is not there)."""
    if not dep:
        return name, None, None, None
    r = estate.resolver
    act = r.action(dep)
    if act is None:
        return name, f"after {dep} is answered", f"pin-gated:{name}:{dep}", None
    before = f"{act.get('owner')}/{act.get('repo')}" if act.get("owner") and act.get("repo") else None
    if r.action_approved(dep):
        return name, f"after {dep} runs", None, before
    kind = (act.get("action") or "").lower()
    if kind == "rename" and act.get("new_name", "").lower() == name.lower() and act.get("repo") \
            and r.same(act.get("owner", ""), login):
        return act["repo"], f"{dep} not approved: pin the current slug", f"pin-current-slug:{act['repo']}:{dep}", None
    return name, f"{dep} not approved", f"pin-blocked:{name}:{dep}", None


def pins(estate: Estate, org: str, *, allow_t3: bool = False, lists_capture: dict | None = None,
         repo_ids: dict | None = None) -> tuple[dict, int]:
    login, row, reg = _gate(estate, org, allow_t3=allow_t3, allow_hold=True)
    checks, jobs, logs, order = [], [], [], {"public": [], "members": []}
    held = _star_held(estate, org) == "hold"  # STANDARD §12.5 #4: a HOLD org's pins only report, as `profile` refuses
    if held:
        logs.append("pins:hold")
    for target, key in (("public", "pins_public"), ("members", "pins_members")):
        entries = reg.get(key) or []
        if len(entries) > MAX_PINS:
            checks.append({"target": target, "check": "count", "result": "fail", "detail": f"{len(entries)} > {MAX_PINS}"})
        label = "Public pins" if target == "public" else "Members-only pins"
        for i, p in enumerate(entries[:MAX_PINS], 1):
            name = p.get("repo") if isinstance(p, dict) else p
            dep = str((p.get("depends_on") if isinstance(p, dict) else "") or "")
            pin, gate, lg, before = _pin_slug(estate, login, name, dep)
            hit = None if dep else estate.alias(f"{login}/{name}")
            if hit:  # the registry writes the final slug; a rename with no depends_on still has to run first
                act = estate.resolver.repo_before(f"{login}/{name}")[1]
                if estate.resolver.repo_action_approved(act):
                    gate, before = f"after {hit[1]} runs", hit[0]
                elif estate.resolver.same(hit[0].split("/")[0], login):
                    pin = hit[0].split("/", 1)[1]
                    gate, lg = f"{hit[1]} not approved: pin the current slug", f"pin-current-slug:{pin}:{hit[1]}"
            if lg:
                logs.append(lg)
            full = f"{login}/{pin}"
            # an approved dependency (gate "after X runs") is pinnable only once the repository's metadata is captured
            # under the final slug: until the move or rename has run, the URL and the ticked set would name a
            # repository that does not exist yet, and the writer knows no `depends_on`
            unrun = bool(gate and gate.endswith(" runs")) and estate.metas.get(estate.resolver.slug(full).lower()) is None
            if estate.meta(full) is None and before and estate.meta(before) is not None:
                full = before  # approved but not yet run: check the repository under its current slug
            m = estate.meta(full)
            vis = estate.visibility(full)
            res, detail = "pass", ""
            if m is None:
                res, detail = "unknown", "no metadata (needs-input:metadata)"
            elif target == "public" and vis == "unknown":
                res, detail = "unknown", "visibility unknown (needs-input:visibility)"
            elif target == "public" and vis != "public":
                res, detail = "fail", f"public pin is {vis}"
            elif target == "public" and estate.exposure(full):
                res, detail = "fail", "exposure repo in a public pin"
            elif m.get("archived") or m.get("fork"):
                res, detail = "warn", "archived" if m.get("archived") else "fork"
            if lg and lg.startswith(("pin-blocked", "pin-gated")):
                res = "blocked"
            elif unrun and res != "fail":
                res, detail = "blocked", f"waits for {dep or (hit or ('', ''))[1]} to run; re-capture and re-plan"
                logs.append(f"pin-gated:{pin}:{dep or (hit or ('', ''))[1]}")
            if held:
                res, detail = "hold", "org on HOLD (STANDARD §12.5 #4): pins only report"
            checks.append({"target": target, "position": i, "repo": pin, "result": res, "detail": detail,
                           "depends_on": dep or None, "gate": gate})
            order[target].append(pin)
            if res in ("fail", "blocked", "hold") or (target == "public" and res == "unknown"):
                continue  # a public pin is set only once it is known to be public (fail closed)
            jobs.append(browser_job(
                f"p{PHASE['pins']}-{login}-pin-{target}-{i}", PHASE["pins"], f"https://github.com/{login}/{pin}",
                [f"Open https://github.com/{login}/{pin} signed in as {USER_LOGIN} (an owner of {login}).",
                 "In the repository header, click the 'Edit Pins' button.",
                 f"In the Edit Pins menu, choose the target '{label}' for {login} and confirm. Leave the other target "
                 "as it is.",
                 f"Open https://github.com/{login} and check that {pin} now shows in the {label.lower()} row."],
                org=login, ui_action="org-pin", depends_on=dep or None,
                note=f"Decision 14 pin {i} of {len(entries)} ({target}); {gate or 'no dependency'}."))
    for target, label, view in (("public", "Public pins", "Public"), ("members", "Members-only pins", "Member")):
        bad = ("fail", "blocked", "unknown", "hold") if target == "public" else ("fail", "blocked", "hold")
        keep = [c["repo"] for c in checks if c.get("target") == target and c.get("repo") and c["result"] not in bad]
        if not keep:
            continue
        listing = "; ".join(f"{i}. {n}" for i, n in enumerate(keep, 1))
        jobs.append(browser_job(
            f"p{PHASE['pins']}-{login}-pin-{target}-order", PHASE["pins"], f"https://github.com/{login}",
            [f"Open https://github.com/{login} and choose 'View as: {view}'.",
             f"Above the pinned row, click 'Customize pins' ({label}).",
             f"Make the ticked set exactly: {listing}. Untick any other repository.",
             "Drag the pins into that order, then click 'Save pins'.",
             f"Reload 'View as: {view}' and screenshot the pinned row into state/screens/{login}/."],
            org=login, ui_action="org-pin-order", note=f"Final {target} pin order from the registry (VER-01 check)."))
    lists = star_list_plan(estate, org, lists_capture=lists_capture, repo_ids=repo_ids, allow_t3=allow_t3)
    failed = any(c["result"] == "fail" for c in checks)
    res = {"command": "org", "action": "pins", "owner": login,
           "result": "fail" if failed else "hold" if held else "ok", "checks": checks,
           "order": order, "jobs": jobs, "star_list": lists, "logs": sorted(set(logs + lists.get("logs", [])))}
    return res, CHECK_FAILED if failed else OK


def _lists_nodes(capture: dict | None) -> list[dict]:
    if not capture:
        return []
    v = capture.get("data", capture).get("viewer") or {}
    return list((v.get("lists") or {}).get("nodes") or [])


def _gql(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _list_complete(node: dict) -> bool:
    """A captured List whose `items` page holds every member (queries/star_lists.graphql reads `items(first: 100)`):
    only then does an absent repository prove it is not on that List."""
    items = node.get("items")
    if not isinstance(items, dict) or not isinstance(items.get("nodes"), list):
        return False
    total = items.get("totalCount")
    return isinstance(total, int) and total <= len([x for x in items["nodes"] if x])


def _estate_list_targets(estate: Estate, nodes: list[dict], *, allow_t3: bool = False) -> dict[str, set[str]]:
    """{favorite (lower): ids of every captured estate star List that some org's plan puts it on}. An
    updateUserListsForItem job replaces the item's whole set, so each org's job carries every estate List the item
    belongs on, and two orgs sharing a favorite never undo each other whichever job runs last."""
    r = estate.resolver
    by_name = {n["name"].lower(): n for n in nodes if n.get("name") and n.get("id")}
    out: dict[str, set[str]] = {}
    for key, reg in (r.registry.get("orgs") or {}).items():
        ent = _star_entry(estate, key, reg or {})
        if not ent or _star_held(estate, key) or r.is_placeholder(key):
            continue
        if len(ent["name"]) > LIST_NAME_MAX or len(ent.get("description") or "") > LIST_DESC_MAX:
            continue  # that org's plan fails and adds nothing
        node = by_name.get(ent["name"].lower())
        if node is None:
            continue  # created later: its own plan, after a re-capture, adds the item with the union then
        for f in public_favorites(estate, reg or {}, allow_t3=allow_t3)[0]:
            out.setdefault(f.lower(), set()).add(node["id"])
    return out


def star_list_plan(estate: Estate, org: str, *, lists_capture: dict | None = None, repo_ids: dict | None = None,
                   planned_new: int | None = None, allow_t3: bool = False) -> dict:
    """Per-org star List (decision 14, SOC-01): read the existing lists first, reuse a same-named list, keep the 32-list
    cap, and add each favorite with the **union** of its current lists, this one and every other estate org's star List
    that also takes it (never only the new id). A capture whose lists or List items are cut short proves nothing about
    membership, so no item job is planned from it (needs-input:star-lists-items-paged)."""
    r = estate.resolver
    login = r.canonical(org)
    reg = r.registry_org(org)
    entry = _star_entry(estate, org, reg)
    held = _star_held(estate, org)
    base = {"org": login, "reads": [{"name": "star-lists", "argv": read_command("star_lists")}], "jobs": [], "pending": [],
            "logs": []}
    if not entry:
        return dict(base, result="none", logs=["star-list:none"])
    if held:
        return dict(base, result="hold", list=entry.get("name"), logs=[f"star-list:{held}"])
    name, desc = entry["name"], entry.get("description") or ""
    errs = []
    if len(name) > LIST_NAME_MAX:
        errs.append(f"name is {len(name)} characters (max {LIST_NAME_MAX})")
    if len(desc) > LIST_DESC_MAX:
        errs.append(f"description is {len(desc)} characters (max {LIST_DESC_MAX})")
    # a star List is public on the account: only the favorites the public slice may name go on it (same rule)
    favs, fav_logs = public_favorites(estate, reg, allow_t3=allow_t3)
    incomplete = any(x.startswith("needs-input:favorite-visibility:") for x in fav_logs)
    out = dict(base, list=name, description=desc, items=favs, errors=errs, logs=sorted(set(fav_logs)))
    if errs:
        return dict(out, result="fail")
    nodes = _lists_nodes(lists_capture)
    if lists_capture is None:
        out["pending"] = [{"why": "read the existing lists first (SOC-01)", "needs": "--lists <star_lists capture>"}]
        return dict(out, result="needs-input", logs=sorted(set(fav_logs) | {"needs-input:star-lists-capture"}))
    total = (lists_capture.get("data", lists_capture).get("viewer") or {}).get("lists", {}).get("totalCount", len(nodes))
    existing = {n["name"].lower(): n for n in nodes if n.get("name")}
    phase = PHASE["lists"]
    cur = existing.get(name.lower())
    if cur is None:
        if total + (planned_new or 1) > MAX_LISTS:
            return dict(out, result="fail", errors=[f"{total} lists exist; adding {planned_new or 1} passes the {MAX_LISTS}-list cap"])
        q = ("mutation($name: String!, $description: String) { createUserList(input: {name: $name, description: "
             "$description, isPrivate: false}) { list { id name slug } } }")
        out["jobs"].append(job(f"p{phase}-{login}-list-create", phase, "star-list", ["gh", "api", "graphql", "-f", f"query={q}",
                               "-f", f"name={name}", "-f", f"description={desc}"], org=USER_LOGIN,
                               note=f"Create the '{name}' star List for {login} (public). Then re-capture lists and re-plan."))
        out["pending"] += [{"item": f, "why": "list id known after the create job and a re-capture"} for f in favs]
        return dict(out, result="incomplete" if incomplete else "ok", logs=sorted(set(fav_logs) | {"star-list:create"}))
    list_id = cur["id"]
    if (cur.get("description") or "") != desc:
        q = (f"mutation {{ updateUserList(input: {{listId: {_gql(list_id)}, description: {_gql(desc)}}}) "
             "{ list { id name description } } }")
        out["jobs"].append(job(f"p{phase}-{login}-list-describe", phase, "star-list", ["gh", "api", "graphql", "-f", f"query={q}"],
                               org=USER_LOGIN, note=f"Align the '{name}' list description with the registry."))
    paged = [n.get("name") or n.get("id") for n in nodes if not _list_complete(n)]
    if total > len(nodes):
        paged.append(f"{total - len(nodes)} list(s) not captured")
    if paged and favs:  # fails closed: a replacement set built from a partial page would drop real memberships
        out["pending"].append({"why": "a captured List is cut short (" + ", ".join(map(str, paged)) + "): its members "
                                      "beyond the page are unknown, so no item job is planned",
                               "needs": "a complete star_lists capture (every List's items.totalCount captured)"})
        return dict(out, result="needs-input", list_id=list_id,
                    logs=sorted(set(fav_logs) | {"needs-input:star-lists-items-paged"}))
    targets = _estate_list_targets(estate, nodes, allow_t3=allow_t3)
    member_of: dict[str, set[str]] = {}
    ids: dict[str, str] = {k.lower(): v for k, v in (repo_ids or {}).items()}
    for n in nodes:
        for it in (n.get("items") or {}).get("nodes") or []:
            if it and it.get("nameWithOwner"):
                member_of.setdefault(it["nameWithOwner"].lower(), set()).add(n["id"])
                if it.get("id"):
                    ids.setdefault(it["nameWithOwner"].lower(), it["id"])
    for f in favs:
        have = member_of.get(f.lower(), set())
        if list_id in have:
            continue
        rid = ids.get(f.lower())
        if not rid:
            o, n = f.split("/", 1)
            out["reads"].append({"name": f"repo-id:{f}", "argv": read_command("repo_id", owner=o, name=n)})
            out["pending"].append({"item": f, "why": "repository node id (pass --repo-ids)"})
            continue
        union = sorted(have | {list_id} | targets.get(f.lower(), set()))
        q = (f"mutation {{ updateUserListsForItem(input: {{itemId: {_gql(rid)}, listIds: [{', '.join(_gql(x) for x in union)}]}}) "
             "{ lists { id name } } }")
        out["jobs"].append(job(f"p{phase}-{login}-list-item-{f.replace('/', '__')}", phase, "star-list",
                               ["gh", "api", "graphql", "-f", f"query={q}"], org=USER_LOGIN,
                               note=f"Add {f} to '{name}', keeping its {len(have)} other list(s) and every estate star "
                                    "List that also takes it (union; never unstar)."))
    return dict(out, result="incomplete" if incomplete else "ok", list_id=list_id)


