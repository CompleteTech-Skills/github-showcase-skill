def user_slice(estate: Estate, login: str, *, allow_t3: bool = False) -> tuple[dict, list[str]]:
    """The public slice of the registry's top-level `profile` for the personal README: no private repository, no
    members-only pin, no why/notes text, no placeholder org, no T3 org before sign-off (OPS-03, q71)."""
    r = estate.resolver
    prof = r.registry.get("profile") or {}
    logs: list[str] = []
    intro = prof.get("intro") or {}

    def entry(full: str) -> dict | None:
        full = r.slug(full)
        if _t3_held(estate, full, allow_t3):
            logs.append(f"t3-signoff:{full}")  # T3 work waits for co-owner sign-off (decision 12, q71)
            return None
        if not estate.is_public(full):
            return None
        mm = estate.meta(full) or {}
        if mm.get("fork") or mm.get("archived"):
            return None
        cur = mm.get("_full") or full
        return {"repo": cur.split("/", 1)[1], "full_name": cur, "url": f"https://github.com/{cur}",
                "description": mm.get("description") or "", "license": _license(mm)}

    pins = []
    for p in (prof.get("pins") or [])[:MAX_PINS]:
        full = p.get("repo") if isinstance(p, dict) else p
        e = entry(full) if full and "/" in full else None
        if e:
            pins.append(e)
        else:
            logs.append(f"featured-dropped:{full}")  # not public, a fork or archived: never named on the profile
    more = []
    for full in prof.get("more_projects") or []:
        e = entry(full) if isinstance(full, str) and "/" in full else None
        if e and e["full_name"] not in {x["full_name"] for x in pins + more}:
            more.append(e)
        elif not e:
            logs.append(f"more-dropped:{full}")
    groups = []
    for g in prof.get("org_directory") or []:
        rows = []
        for o in (g or {}).get("orgs") or []:
            if not isinstance(o, str):
                continue
            st = r.owner_status(o)
            if r.is_placeholder(o) or st == "excluded":
                continue  # q71: placeholder orgs are left out
            if st == "t3" and not allow_t3:
                logs.append(f"t3-signoff:{o}")
                continue
            try:
                row = r.brand_org(o)
            except NeedsInput:
                logs.append(f"needs-input:org:{o}")
                continue
            hold = bool(_star_held(estate, o))
            tile = not hold and ((_tier(row) == "T1" and bool(row.get("flagship"))) or (_tier(row) == "T2" and not rows))
            try:
                rdesc = (r.registry_org(o).get("profile") or {}).get("description") or ""
            except NeedsInput:
                rdesc = ""
            rows.append({"login": r.canonical(o), "name": row.get("display_name") or r.canonical(o),
                         "description": "" if hold else _short_desc(row.get("description") or rdesc), "tile": tile,
                         "brand_key": r.brand_key(o) or o})
        if rows:
            groups.append({"group": g.get("group") or "", "orgs": rows})
    # tech stack and latest activity, computed from the public slice only (kit rule 5: say what is counted)
    langs: dict[str, int] = {}
    recent = []
    shown_orgs = {o["login"].lower() for g in groups for o in g["orgs"]}
    for m in estate.metas.values():
        full = m["_full"]
        if m["_owner"].lower() not in shown_orgs or not estate.is_public(full) or m.get("fork"):
            continue
        for lang, n in (m.get("languages") or {}).items():
            if isinstance(n, int):
                langs[lang] = langs.get(lang, 0) + n
        if not m.get("archived"):
            recent.append((_last(m), full, m.get("description") or ""))
    total = sum(langs.values()) or 1
    stack = [{"language": k, "share": round(100 * v / total, 1)} for k, v in sorted(langs.items(), key=lambda x: -x[1])[:12]]
    recent.sort(key=lambda x: (x[0], x[1]), reverse=True)
    if not stack:
        logs.append("needs-input:languages (no public metadata with `languages`)")
    email = prof.get("email") or STEWARD_EMAIL
    socials = [s for s in prof.get("socials") or [] if isinstance(s, dict) and s.get("url", "").startswith("https://")]
    data = {"std": STANDARD, "user": login, "name": prof.get("name") or intro.get("headline") or login,
            "intro": {k: intro.get(k) for k in ("eyebrow", "headline", "tagline", "chips") if intro.get(k)},
            "who_what": (prof.get("who_what") or "").strip(), "company": prof.get("company") or "",
            "blog": prof.get("blog") or "", "location": prof.get("location") or "", "email": email,
            "socials": socials, "pins": pins, "more_projects": more, "org_directory": groups, "tech_stack": stack,
            "latest": [{"full_name": f, "url": f"https://github.com/{f}", "description": d, "updated": u[:10]}
                       for u, f, d in recent[:8] if u],
            "public_org_count": sum(len(g["orgs"]) for g in groups)}
    if not data["who_what"]:
        logs.append("needs-input:who-what")
    return data, logs


