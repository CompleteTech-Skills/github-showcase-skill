class Estate:
    """Brand, resolver, repository metadata and flags: everything the org actions read, loaded once."""

    def __init__(self, brand, resolver: Resolver, metas: dict | None = None, flags: dict | None = None):
        self.brand, self.resolver = brand, resolver
        self.metas: dict[str, dict] = {}
        for raw in (metas or {}).values():
            self.add_meta(raw)
        self.flags: dict[str, list] = {}
        for k, v in (flags or {}).items():  # two spellings of one slug (an old and a new login) keep both lists
            self.flags.setdefault(resolver.slug(k).lower(), []).extend(v or [])

    def add_meta(self, raw: dict, path: str | None = None) -> None:
        owner = raw.get("owner")
        owner = owner.get("login") if isinstance(owner, dict) else owner
        if not owner and raw.get("full_name"):
            owner = raw["full_name"].split("/")[0]
        repo = raw.get("repo") or raw.get("name") or (raw.get("full_name") or "/").split("/")[1]
        if not owner or not repo:
            return
        full = self.resolver.slug(f"{owner}/{repo}")
        rec = dict(raw, _full=full, _owner=full.split("/")[0], _repo=repo)
        if path:
            rec["_path"] = path
        self.metas[full.lower()] = rec

    def meta(self, full: str) -> dict | None:
        m = self.metas.get(self.resolver.slug(full).lower())
        if m is None:
            hit = self.alias(full)
            m = self.metas.get(self.resolver.slug(hit[0]).lower()) if hit else None
        return m

    def alias(self, full: str) -> tuple[str, str] | None:
        """(slug today, action id) when the registry names a repository by the slug a pending rename or transfer gives it
        and only the current slug has metadata. A rename inside the org always resolves (the repository is homed here
        either way, and GitHub redirects the old URL once it runs); a transfer from another org resolves only once
        approved, because until then the repository is not in this org."""
        r = self.resolver
        cur, seen, ids = full, set(), []
        while (hit := r.repo_before(cur)) and cur.lower() not in seen:
            seen.add(cur.lower())
            old, act = hit
            if not r.same(old.split("/")[0], cur.split("/")[0]) and not r.repo_action_approved(act):
                return None
            ids.append(str(act.get("id") or act.get("action")))
            cur = old
            if self.metas.get(r.slug(cur).lower()) is not None:
                return r.slug(cur), "+".join(ids)
        return None

    def pending_move(self, full: str) -> str | None:
        """The action id when the registry homes a repository here only after a transfer from another org that is not
        approved yet: it is not in this org today, so its missing metadata says nothing about this org's visibility."""
        r = self.resolver
        hit = r.repo_before(full)
        if hit and not r.same(hit[0].split("/")[0], full.split("/")[0]) and not r.repo_action_approved(hit[1]):
            return str(hit[1].get("id") or hit[1].get("action"))
        return None

    def current(self, full: str) -> str:
        """The slug a repository has today (its metadata's), else the slug as given."""
        m = self.meta(full)
        return (m or {}).get("_full") or self.resolver.slug(full)

    def repos_of(self, org: str) -> list[str]:
        """Repository names homed in the org: the registry's final_repos (decision 5: one home), or, for an org
        whose row lists none, every captured repository of that owner."""
        login = self.resolver.canonical(org)
        names = list(self.resolver.registry_org(org).get("final_repos") or [])
        if names:
            return names
        seen: set[str] = set()
        for m in self.metas.values():
            if self.resolver.same(m["_owner"], login) and m["_repo"].lower() not in seen:  # captured under an old login
                names.append(m["_repo"])
                seen.add(m["_repo"].lower())
        return names

    # -- classification ----------------------------------------------------------------------------------
    def visibility(self, full: str) -> str:
        m = self.meta(full)
        if not m or (m.get("error") and "visibility" not in m and "private" not in m):
            return "unknown"
        return m.get("visibility") or ("private" if m.get("private") else ("public" if "private" in m else "unknown"))

    def exposure(self, full: str) -> bool:
        """A flag under any slug the repository has had or will have: today's, the registry's final one, and the slug
        before a pending or executed rename or transfer (decisions.json keys a flag by the slug it was reviewed under)."""
        r = self.resolver
        slugs = {r.slug(full).lower(), self.current(full).lower()}
        for s in list(slugs):
            if hit := r.repo_before(s):
                slugs.add(r.slug(hit[0]).lower())
        slugs |= {k for k, (old, _a) in getattr(r, "_repo_before", {}).items() if r.slug(old).lower() in slugs}
        flags = [f for s in slugs for f in self.flags.get(s, [])]
        return any(EXPOSURE.search(str(f)) and "false-positive" not in str(f).lower() for f in flags)

    def owns(self, owner: str) -> bool:
        """An estate owner under any of its logins (registry or brand row, the steward account, a registry placeholder
        or merge-source org, or an excluded, HOLD, T3 or watching owner): its repositories are subject to the
        public-slice rules wherever they are named."""
        r = self.resolver
        return bool(owner) and (r.registry_key(owner) is not None or r.brand_key(owner) is not None
                                or r.same(owner, USER_LOGIN) or r.is_placeholder(owner)
                                or not r.same(r.successor(owner), owner)
                                or r.owner_status(owner) in ("excluded", "hold", "t3", "watching"))

    def is_public(self, full: str) -> bool:
        """The public slice (OPS-03): public, not on HOLD, not an exposure repo. Unknown visibility fails closed."""
        owner = full.split("/")[0]
        if self.visibility(full) != "public" or self.exposure(full):
            return False
        return self.resolver.owner_status(owner) not in ("hold", "excluded") and not self.resolver.family_hold(owner)


def load_metas(meta_dir: str | Path | None, estate: Estate) -> int:
    """Load every *.json under meta_dir, recursively (one repository each, or a list), into the estate, so
    `--meta-dir state/meta` also finds repositories whose metadata is still filed under the owner they leave by an
    approved transfer. Returns the count."""
    if not meta_dir:
        return 0
    d = Path(meta_dir)
    if not d.is_dir():
        raise ShowcaseError(f"--meta-dir {d} is not a directory", log="usage")
    n = 0
    for p in sorted(d.rglob("*.json")):
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except ValueError:
            continue
        for raw in data if isinstance(data, list) else [data]:
            if isinstance(raw, dict):
                estate.add_meta(raw, str(p))
                n += 1
    return n


def load_flags(decisions_json: str | Path | None) -> dict:
    """{owner/repo: [flags]} from decisions/decisions.json (exposure repos stay out of the public slice). Each item's
    flags are keyed by the slug it was reviewed under and by the slug its move or rename gives it
    (`target_owner`/`new_name`), so a flag still applies once the repository is re-captured under its new slug."""
    if not decisions_json or not Path(decisions_json).is_file():
        return {}
    data = json.loads(Path(decisions_json).read_text(encoding="utf-8"))
    out: dict[str, list] = {}
    for it in data if isinstance(data, list) else []:
        if isinstance(it, dict) and it.get("owner") and it.get("repo"):
            flags = list(it.get("flags") or [])
            keys = {f"{it['owner']}/{it['repo']}", f"{it.get('target_owner') or it['owner']}/{it.get('new_name') or it['repo']}"}
            for k in sorted(keys):
                out.setdefault(k, []).extend(x for x in flags if x not in out.get(k, []))
    return out


