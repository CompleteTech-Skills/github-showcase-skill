from __future__ import annotations

import re

from .readme import normalize_text

WINDOW = 20
GEN_RE = re.compile(
    r"(?i)(?:do\s+not\s+(?:manually\s+)?edit|don'?t\s+edit|autogenerated|auto-generated"
    r"|generated\s+(?:by|from|with|using)\b|@generated\b|this\s+file\s+is\s+(?:automatically\s+)?generated)"
)
FM_FLAG_RE = re.compile(r"(?im)^\s*(?:auto_?generated|generated)\s*:\s*(?:true|yes)\s*$")
COMMENT_RE = re.compile(r"<!--(.*?)-->", re.S)


def _front_matter(lines: list[str]) -> list[str] | None:
    """The lines between a leading `---` and the next `---` inside the window, or None when there is no such block."""
    if not lines or lines[0].strip() != "---":
        return None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i]
    return None


def _blank_fences(lines: list[str]) -> list[str]:
    out, in_fence = [], False
    for line in lines:
        s = line.strip()
        if s.startswith("```") or s.startswith("~~~"):
            in_fence = not in_fence
            out.append("")
        elif in_fence:
            out.append("")
        else:
            out.append(line)
    return out


def detect(text: str) -> str | None:
    """'front-matter' or 'header' when the README says it is generated or managed, else None. Returns no file text."""
    lines = normalize_text(text).split("\n")[:WINDOW]
    fm = _front_matter(lines)
    if fm is not None:
        if any(GEN_RE.search(line) for line in fm) or FM_FLAG_RE.search("\n".join(fm)):
            return "front-matter"
    joined = "\n".join(_blank_fences(lines))
    for m in COMMENT_RE.finditer(joined):
        body = m.group(1).strip()
        if body.lower().startswith("showcase:"):
            continue
        if GEN_RE.search(body):
            return "header"
    return None


def managed_reason(ctx, text: str) -> str | None:
    """Why `readme --write` must refuse this README: 'config' for `readme: managed`, a detection reason, or None.
    `readme: authored` in .github/showcase.yml turns detection off for the repository."""
    v = (getattr(ctx, "override", None) or {}).get("readme")
    if v == "authored":
        return None
    if v == "managed":
        return "config"
    return detect(text)
