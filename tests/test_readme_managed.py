"""README ownership: `readme: managed|authored`, generated-header and front-matter refusal (`readme --write`, exit 4).

Fixtures are synthetic (Northwind Trading Co.) and written into tmp_path."""
import json
import os

import pytest

from ctshowcase.config import parse_repo_override
from ctshowcase.content import readme_managed_reason
from ctshowcase.errors import ConfigError
from conftest import EX, run_cli

META = EX / "meta" / "northwind-support-triage-agent.json"
GENERATED = "<!-- Generated by the Northwind tool -->\n# Support triage\n\nBody text.\n"
PLAIN = "# Support triage\n\nBody text.\n"


def snapshot(root):
    out = {}
    for dirpath, _, names in os.walk(root):
        for name in names:
            path = os.path.join(dirpath, name)
            with open(path, "rb") as fh:
                out[os.path.relpath(path, root)] = fh.read()
    return out


# -- detector ---------------------------------------------------------------------------------------

@pytest.mark.parametrize("comment", [
    "<!-- Generated by tool -->",
    "<!-- generated from schema.yaml -->",
    "<!-- Generated With the builder -->",
    "<!-- generated using x -->",
    "<!-- auto-generated, do not edit -->",
    "<!-- @generated -->",
    "<!-- DO NOT EDIT -->",
])
def test_header_comment_triggers_refusal(comment):
    assert readme_managed_reason(f"{comment}\n# Title\n") == "header"


def test_front_matter_marks_generated():
    text = "---\ntitle: Support\ngenerated: true\n---\n# Support triage\n"
    assert readme_managed_reason(text) == "front-matter"
    assert readme_managed_reason("---\ntitle: Support\n# note: @generated by tool\n---\n# T\n") == "front-matter"


def test_front_matter_without_mark_is_not_refused():
    assert readme_managed_reason("---\ntitle: Support\ngenerated: false\n---\n# Support triage\n") is None


def test_config_managed_refuses_a_plain_readme():
    assert readme_managed_reason(PLAIN, {"readme": "managed"}) == "config"


def test_authored_overrides_a_header_and_front_matter():
    assert readme_managed_reason(GENERATED, {"readme": "authored"}) is None
    assert readme_managed_reason("---\ngenerated: true\n---\n# T\n", {"readme": "authored"}) is None


def test_override_holds_one_mode_value():
    # `readme` is one value: `managed` refuses, `authored` lifts the header refusal
    assert readme_managed_reason(GENERATED, {"readme": "managed"}) == "config"
    assert readme_managed_reason(GENERATED, {"readme": "authored"}) is None


@pytest.mark.parametrize("override", [None, {}, {"readme": None}, {"readme": {"header": True}},
                                      {"readme": {"header": True, "footer": False}}])
def test_dict_and_null_values_do_not_raise_or_mode(override):
    assert readme_managed_reason(PLAIN, override) is None
    assert readme_managed_reason(GENERATED, override) == "header"


def test_fenced_code_mention_is_ignored():
    text = "```markdown\n<!-- Generated by the tool -->\n```\n# Support triage\n"
    assert readme_managed_reason(text) is None
    tilde = "~~~\n<!-- DO NOT EDIT -->\n~~~\n# Support triage\n"
    assert readme_managed_reason(tilde) is None


def test_fence_does_not_hide_a_real_header_after_it():
    text = "```\ncode\n```\n<!-- Generated by tool -->\n# T\n"
    assert readme_managed_reason(text) == "header"


def test_showcase_marker_is_ignored():
    text = "<!-- showcase:banner:start -->\n<img>\n<!-- showcase:banner:end -->\n# Support triage\n"
    assert readme_managed_reason(text) is None


def test_header_at_line_21_is_not_detected():
    lines = ["# Support triage"] + [f"line {i}" for i in range(2, 21)]
    assert readme_managed_reason("\n".join(lines + ["<!-- Generated by tool -->"]) + "\n") is None
    at_20 = "\n".join(lines[:19] + ["<!-- Generated by tool -->"]) + "\n"
    assert readme_managed_reason(at_20) == "header"


def test_plain_readme_is_not_refused():
    assert readme_managed_reason(PLAIN) is None
    assert readme_managed_reason(PLAIN, {"readme": {"header": True}}) is None


# -- schema -----------------------------------------------------------------------------------------

@pytest.mark.parametrize("text, expected", [
    ("readme: managed\n", {"readme": "managed"}),
    ("readme: authored\n", {"readme": "authored"}),
    ("readme: null\n", {"readme": None}),
    ("readme: {header: true}\n", {"readme": {"header": True}}),
    ("readme: {footer: false}\n", {"readme": {"footer": False}}),
])
def test_schema_accepts_managed_authored_null_and_object(text, expected):
    assert parse_repo_override(".github/showcase.yml", text) == expected


@pytest.mark.parametrize("text", [
    "readme: bogus\n",
    "readme: 3\n",
    "readme: [managed]\n",
    "readme: Managed\n",
    "readme: {header: maybe}\n",
    "readme: {header: true, extra: 1}\n",
])
def test_schema_rejects_other_values(text):
    with pytest.raises(ConfigError):
        parse_repo_override(".github/showcase.yml", text)


# -- CLI --------------------------------------------------------------------------------------------

def test_write_refuses_a_generated_readme_and_writes_nothing(tmp_path):
    (tmp_path / "README.md").write_text(GENERATED, encoding="utf-8")
    before = snapshot(tmp_path)
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--write", "--records", tmp_path / "rec.jsonl")
    assert p.returncode == 4, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert out["result"] == "needs-input"
    assert "needs-input:readme-managed" in out["logs"] and "readme-managed:header" in out["logs"]
    assert snapshot(tmp_path) == before
    assert not (tmp_path / "rec.jsonl").exists()


def test_bootstrap_write_refuses_and_writes_nothing(tmp_path):
    (tmp_path / "README.md").write_text(GENERATED, encoding="utf-8")
    (tmp_path / ".github").mkdir()
    (tmp_path / ".github" / "showcase.yml").write_text("readme: managed\n", encoding="utf-8")
    before = snapshot(tmp_path)
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--bootstrap", "--write",
                "--records", tmp_path / "rec.jsonl")
    assert p.returncode == 4, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert out["result"] == "needs-input"
    assert "readme-managed:config" in out["logs"]
    assert snapshot(tmp_path) == before


def test_front_matter_write_refusal(tmp_path):
    (tmp_path / "README.md").write_text("---\ngenerated: true\n---\n# Support triage\n", encoding="utf-8")
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--write")
    assert p.returncode == 4
    assert "readme-managed:front-matter" in json.loads(p.stdout)["logs"]


def test_dry_run_still_shows_the_diff_with_the_same_logs(tmp_path):
    (tmp_path / "README.md").write_text(GENERATED, encoding="utf-8")
    before = snapshot(tmp_path)
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme")
    assert p.returncode == 0, p.stderr
    out = json.loads(p.stdout)
    assert out["diff"].startswith("--- a/README.md")
    assert "needs-input:readme-managed" in out["logs"] and "readme-managed:header" in out["logs"]
    assert out["written"] is False
    assert snapshot(tmp_path) == before


def test_authored_writes_a_generated_readme(tmp_path):
    (tmp_path / "README.md").write_text(GENERATED, encoding="utf-8")
    (tmp_path / ".github").mkdir()
    (tmp_path / ".github" / "showcase.yml").write_text("readme: authored\n", encoding="utf-8")
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--write")
    assert p.returncode == 0, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert "needs-input:readme-managed" not in out["logs"]
    assert (tmp_path / "README.md").read_text(encoding="utf-8") != GENERATED


def test_plain_readme_write_is_not_refused(tmp_path):
    (tmp_path / "README.md").write_text(PLAIN, encoding="utf-8")
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--write")
    assert p.returncode == 0, p.stdout + p.stderr
    assert "readme-managed" not in " ".join(json.loads(p.stdout)["logs"])
