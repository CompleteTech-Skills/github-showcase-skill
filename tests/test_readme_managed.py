"""Issue #71: a README a generator owns is never rewritten by `readme --write` (any mode, --bootstrap included).

Fixtures are synthetic Northwind READMEs. The detection signals are a generated-file HTML comment in the first 20
lines, front matter that says generated, and `readme: managed` in `.github/showcase.yml`; `readme: authored` switches
detection off.
"""
import json

import pytest

from conftest import EX, run_cli
from ctshowcase import readme_managed as RM
from ctshowcase.errors import ConfigError

META = EX / "meta" / "northwind-support-triage-agent.json"
BODY = "# Support triage agent\n\nRuns the Northwind triage queue.\n\n## Usage\n\nRun it.\n"

HEADERS = ["<!-- Generated by docs-build 2.1 -->", "<!-- DO NOT EDIT -->", "<!-- auto-generated from templates/ -->",
           "<!-- @generated -->", "<!--\n  This file is AUTOGENERATED.\n  do not edit by hand\n-->",
           "<!-- `DO NOT EDIT` -->"]  # backticks inside a real comment do not hide it


def repo(tmp_path, readme, config=None):
    (tmp_path / "README.md").write_text(readme, encoding="utf-8")
    if config is not None:
        (tmp_path / ".github").mkdir(exist_ok=True)
        (tmp_path / ".github" / "showcase.yml").write_text(config, encoding="utf-8")
    return tmp_path


def readme_cmd(tmp_path, *args):
    return run_cli("--meta", META, "--repo-dir", tmp_path, "--format", "json", "readme", *args)


def snapshot(tmp_path):
    return sorted((str(p.relative_to(tmp_path)), p.read_bytes()) for p in tmp_path.rglob("*") if p.is_file())


@pytest.mark.parametrize("header", HEADERS)
@pytest.mark.parametrize("flags", [("--mode", "upgrade"), ("--mode", "scaffold"), ("--mode", "header"), ("--bootstrap",)])
def test_header_comment_blocks_every_write_mode(tmp_path, header, flags):
    repo(tmp_path, header + "\n" + BODY)
    (tmp_path / "CONTRIBUTING.md").write_text("# Contributing\n", encoding="utf-8")
    before = snapshot(tmp_path)
    p = readme_cmd(tmp_path, *flags, "--write", "--records", tmp_path / "records.json")
    assert p.returncode == 4, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert out["result"] == "needs-input"
    assert {"needs-input:readme-managed", "readme-managed:header"} <= set(out["logs"])
    assert out["written"] is False
    assert snapshot(tmp_path) == before  # no README, CONTRIBUTING, badge or --records file written


def test_front_matter_and_config_sources(tmp_path):
    repo(tmp_path, "---\ntitle: Triage\ngenerated: true\n---\n" + BODY)
    out = json.loads(readme_cmd(tmp_path, "--mode", "header", "--write").stdout)
    assert "readme-managed:front-matter" in out["logs"]
    repo(tmp_path, BODY, "readme: managed\n")
    p = readme_cmd(tmp_path, "--mode", "header", "--write")
    assert p.returncode == 4
    assert "readme-managed:config" in json.loads(p.stdout)["logs"]
    assert (tmp_path / "README.md").read_text(encoding="utf-8") == BODY


def test_dry_run_still_previews_with_the_same_logs(tmp_path):
    repo(tmp_path, "<!-- Generated by docs-build -->\n" + BODY)
    p = readme_cmd(tmp_path, "--mode", "upgrade")
    assert p.returncode == 0, p.stderr
    out = json.loads(p.stdout)
    assert out["diff"] and out["written"] is False
    assert {"needs-input:readme-managed", "readme-managed:header"} <= set(out["logs"])
    text = run_cli("--meta", META, "--repo-dir", tmp_path, "--format", "text", "readme", "--mode", "upgrade")
    assert text.returncode == 0 and "+++ b/README.md" in text.stdout
    assert "readme-managed:header" in text.stderr


def test_authored_switches_detection_off(tmp_path):
    repo(tmp_path, "<!-- DO NOT EDIT -->\n" + BODY, "readme: authored\n")
    p = readme_cmd(tmp_path, "--mode", "upgrade", "--write")
    assert p.returncode == 0, p.stdout
    assert not any("readme-managed" in x for x in json.loads(p.stdout)["logs"])
    assert "showcase:" in (tmp_path / "README.md").read_text(encoding="utf-8")


@pytest.mark.parametrize("text", [
    BODY,
    "<!-- showcase:header:start -->\nx\n<!-- showcase:header:end -->\n" + BODY,
    BODY.replace("Run it.", "Generated by hand, do not edit lightly."),  # prose, not an HTML comment
    "\n" * 25 + "<!-- Generated by docs-build -->\n" + BODY,  # past the first 20 lines
    "---\ngenerated: false\n---\n" + BODY,
    "---\ntitle: x\n---\n" + BODY,
    BODY + "\n```\n<!-- DO NOT EDIT -->\n```\n",
    # markdown-magic section delimiters: only the TOC is generated, the README is authored
    "# Proj\n\n<!-- AUTO-GENERATED-CONTENT:START (TOC) -->\n- [Usage](#usage)\n<!-- AUTO-GENERATED-CONTENT:END -->\n\n## Usage\nhi\n",
    # an indented (4-space) code example of a header is documentation
    "# Proj\n\nExample generated-file header:\n\n    <!-- DO NOT EDIT -->\n\n## Usage\nhi\n",
    "# Proj\n\nUse `<!-- DO NOT EDIT -->` in generated files.\n",
])
def test_ordinary_readmes_are_not_managed(text):
    assert RM.source(text, {}) is None


def test_readme_config_values_in_the_schema(tmp_path):
    for value, ok in (("managed", True), ("authored", True), ("null", True), ("other", False), ("true", False)):
        repo(tmp_path, BODY, f"readme: {value}\n")
        p = readme_cmd(tmp_path, "--mode", "header")
        assert (p.returncode == 0) is ok, (value, p.stdout)
        if not ok:
            assert p.returncode == 2
    repo(tmp_path, BODY, "readme:\n  header: true\n")  # the older mapping keeps validating
    assert readme_cmd(tmp_path, "--mode", "header").returncode == 0


def test_config_mode_ignores_the_legacy_mapping():
    assert RM.config_mode({"readme": {"header": True}}) is None
    assert RM.config_mode({"readme": "managed"}) == "managed"
    assert issubclass(ConfigError, Exception)


def test_action_skips_the_managed_exit_with_a_warning():
    """The composite Action turns exit 4 + needs-input:readme-managed into a warning (skipped=1), not a failure."""
    from conftest import ROOT
    text = (ROOT / "action.yml").read_text(encoding="utf-8")
    assert '"$rc" -eq 4' in text and "needs-input:readme-managed" in text
    assert "README skipped: it is generated" in text and "readme_managed=true" in text


@pytest.mark.parametrize("text", [
    '---\n"generated": true\n---\n' + BODY,
    "---\n  generated: true\n---\n" + BODY,
    "---\nGenerated_By: docs-build # tool\n---\n" + BODY,
])
def test_front_matter_is_decoded_as_yaml(text):
    assert RM.source(text, {}) == "front-matter"


def test_inline_code_does_not_hide_a_real_header():
    assert RM.source("```npm run docs``` first\n<!-- Generated by docs -->\n" + BODY, {}) == "header"


def test_managed_dry_run_previews_even_when_preservation_objects(tmp_path):
    # a tagline block with text the metadata would replace trips readme-shrink on an unmanaged README (exit 1);
    # on a managed one the dry run is only a preview, so it still prints the diff with exit 0 (acceptance 2)
    text = ("<!-- Generated by docs -->\n# T\n\n<!-- showcase:tagline:start -->\n**Old description**\n"
            "<!-- showcase:tagline:end -->\n" + BODY)
    repo(tmp_path, text)
    p = readme_cmd(tmp_path, "--mode", "upgrade")
    assert p.returncode == 0, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert out["written"] is False and "readme-managed:header" in out["logs"]
    assert (tmp_path / "README.md").read_text(encoding="utf-8") == text


@pytest.mark.parametrize("text", [
    # review: backticks inside a comment are not a Markdown fence, so they cannot hide the real header after it
    "<!--\nExample syntax uses a fence:\n```\n-->\n<!-- Generated by docs-build. DO NOT EDIT. -->\n" + BODY,
    # review: a section-style comment that says the entire file is generated is still a whole-file warning
    "<!-- README:START - This entire file is auto-generated. DO NOT EDIT. -->\n" + BODY,
])
def test_comment_interiors_are_opaque_and_whole_file_section_comments_count(text):
    assert RM.source(text, {}) == "header"


@pytest.mark.parametrize("text", [
    # review: CommonMark inline code may span a line break; this is documentation, not a generated header
    "Use `<!--\nDO NOT EDIT\n-->` for generated files.\n" + BODY,
    "<!-- AUTO-GENERATED-CONTENT:START (TOC) -->\n- a\n<!-- AUTO-GENERATED-CONTENT:END -->\n" + BODY,
    "```html\n<!-- DO NOT EDIT -->\n```\n" + BODY,
])
def test_documented_examples_and_section_regions_stay_authored(text):
    assert RM.source(text, {}) is None
