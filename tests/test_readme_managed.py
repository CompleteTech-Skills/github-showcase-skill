"""Regression coverage for generated taglines and repository-managed READMEs."""
import json

import pytest

from conftest import meta_dict, run_cli
from ctshowcase import readme

OLD = "Run the previous workflow for teams."
NEW = "Run the current workflow for teams."
GENERATED_README = """<!--
Generated by scripts/build_docs.py.
DO NOT EDIT.
-->
# Workflow guide

## Usage

Run the workflow from the project directory.
"""


def write_meta(path, description):
    path.write_text(json.dumps(meta_dict(description=description)), encoding="utf-8")


def test_default_write_refreshes_generated_tagline(tmp_path):
    checkout = tmp_path / "checkout"
    checkout.mkdir()
    meta = tmp_path / "meta.json"
    write_meta(meta, OLD)
    args = ("--meta", meta, "--repo-dir", checkout, "readme", "--write")
    result = run_cli(*args)
    assert result.returncode == 0, result.stderr
    path = checkout / "README.md"
    before = path.read_text(encoding="utf-8").replace(
        readme.wrap("tagline", f"**{OLD}**"),
        readme.wrap("tagline", f"**{OLD}**") + f"\n\n**{OLD}**",
    )
    path.write_text(before, encoding="utf-8")
    write_meta(meta, NEW)
    result = run_cli(*args)
    assert result.returncode == 0, result.stdout
    assert json.loads(result.stdout)["mode"] == "upgrade"
    after = path.read_text(encoding="utf-8")
    assert readme.wrap("tagline", f"**{NEW}**") in after
    assert after.count(f"**{OLD}**") == 1


def test_generated_replacement_cannot_count_as_authored_line():
    before = readme.wrap("tagline", f"**{OLD}**") + f"\n**{NEW}**\n"
    after = readme.wrap("tagline", f"**{NEW}**")
    assert f"lost line: **{NEW}**" in readme.preservation(before, after, [])


def test_tagline_marker_example_is_not_owned():
    fence = chr(96) * 3
    example = f"{fence}html\n" + readme.wrap("tagline", f"**{OLD}**") + f"\n{fence}\n"
    assert f"lost line: **{OLD}**" in readme.preservation(example, f"{fence}html\n{fence}\n", [])


@pytest.mark.parametrize("mode", ["header", "upgrade"])
def test_tagline_block_with_authored_prose_survives(make_ctx, mode):
    ctx = make_ctx(description=NEW)
    block = readme.wrap("tagline", f"**{OLD}**\n\n\nAuthored note.")
    before = f"# Workflow guide\n\n{block}\n\n## Usage\nBody.\n"
    if mode == "header":
        after = readme.header_only(ctx, before)
    else:
        after, removed = readme.upgrade(ctx, before)
        assert not readme.preservation(before, after, removed)
    assert block in after


@pytest.mark.parametrize("notice", [
    "<!-- DO NOT EDIT -->",
    "DO NOT EDIT: generated documentation",
    "<!-- Generated\nby scripts/build_docs.py -->",
    "---\ngenerated_by: scripts/build_docs.py\n---",
    "---\nnotice: DO NOT EDIT\n...",
    "\n" * 19 + "<!-- Generated by scripts/build_docs.py -->",
])
def test_managed_notice(make_ctx, notice):
    assert readme.managed_reason(make_ctx(), f"{notice}\n# Workflow guide\n")


@pytest.mark.parametrize("text", [
    "# Workflow guide\n\nThe summary is generated by a helper.",
    "The field is named `<!-- Generated by scripts/build_docs.py -->`.",
    "\x60\x60\x60html\n<!-- Generated by scripts/build_docs.py -->\n\x60\x60\x60",
    "\n" * 20 + "<!-- Generated by scripts/build_docs.py -->",
])
def test_prose_code_and_late_comments_are_not_ownership_notices(make_ctx, text):
    assert readme.managed_reason(make_ctx(), text) is None


@pytest.mark.parametrize("managed_by", ["notice", "config"])
def test_managed_cli_write_refuses_and_dry_run_offers_header(tmp_path, managed_by):
    checkout = tmp_path / "checkout"
    checkout.mkdir()
    if managed_by == "config":
        (checkout / ".github").mkdir()
        (checkout / ".github/showcase.yml").write_text("readme:\n  managed: true\n", encoding="utf-8")
        original = GENERATED_README.split("-->\n")[1]
    else:
        original = GENERATED_README
    path = checkout / "README.md"
    path.write_bytes(original.encode())
    meta, records = tmp_path / "meta.json", tmp_path / "records.jsonl"
    write_meta(meta, NEW)
    opts = ("--meta", meta, "--repo-dir", checkout)
    args = ("readme", "--badges", "local", "--variant", "F", "--records", records)

    for argv, expected_exit in [((*opts, *args, "--write"), 4), ((*opts, *args), 0)]:
        result = run_cli(*argv)
        assert result.returncode == expected_exit, (result.stderr, result.stdout)
        payload = json.loads(result.stdout)
        assert payload["result"] == "needs-input"
        assert payload["written"] is False
        assert "needs-input:readme-managed" in payload["logs"]
        assert f'<p align="center"><b>{NEW}</b></p>' in payload["proposed_header"]
        assert "docs/images/badges/" in payload["proposed_header"]

    result = run_cli("--format", "text", *opts, *args)
    assert result.returncode == 0, result.stderr
    assert "needs-input:readme-managed" in result.stderr
    assert f'<p align="center"><b>{NEW}</b></p>' in result.stdout
    assert path.read_bytes() == original.encode()
    assert not (checkout / "docs").exists()
    assert not records.exists()
