BASE_PROVENANCE = """## assets/icon.png
- Date: YYYY-MM-DD
- Tool and model: TOOL / MODEL ID AND VERSION
- Seed: SEED or "not supported"
- Reference images: golden reference path, jev-reference.png, or "none"
- Prompt: (verbatim, fenced)
- Candidates: 4 or 8; selected: N (reason: one line)
- Post-processing: showcase.py VERSION; output sha256 HASH; size KB
"""

# A local path an operator could paste into the recipe: POSIX absolute or home-relative,
# Windows drive-rooted (backslash or slash) or UNC. Each must start a token (after
# whitespace, a backtick, a quote, a parenthesis or "="), so URLs and mid-word slashes
# such as art/prompts/ORG/REPO do not match.
LOCAL_PATH = re.compile(
    r"(?:^|[\s`'\"(=])[A-Za-z]:[\\/]"        # C:\x or C:/x
    r"|(?:^|[\s`'\"(=])\\\\[A-Za-z0-9_.-]"   # \\server\share
    r"|(?:^|[\s`'\"(=])~?/[A-Za-z0-9_.-]",   # /tmp/x, /home/x or ~/x
    re.M,
)


def _text():
    return ART.read_text(encoding="utf-8")


def _recipe(text):
    start = text.find(HEAD)
    if start < 0:
        return ""
    body = text[start + len(HEAD):]
    m = re.search(r"^## ", body, re.M)
    return HEAD + body[: m.start()] if m else HEAD + body


def _outside_recipe(text):
    recipe = _recipe(text)
    assert recipe, "recipe section not found"
    return text.replace(recipe, "", 1)


def test_recipe_section_exists_before_glyph_template():
    text = _text()
    assert text.count(HEAD) == 1, "recipe heading must appear exactly once"
    assert text.find(HEAD) < text.find(GLYPH)
    assert _recipe(text), "recipe section not found"


def test_recipe_has_codex_exec_command():
    section = _recipe(_text())
    assert "codex exec" in section
    assert "--json" in section
    assert "--skip-git-repo-check" in section
    fence = re.search(r"```bash\n(.*?)```", section, re.S)
    assert fence, "command must sit in a ```bash fence"
    assert "codex exec" in fence.group(1)
    assert "--json" in fence.group(1)
    assert "--skip-git-repo-check" in fence.group(1)


def test_recipe_reads_path_from_run_output_not_newest():
    lowered = _recipe(_text()).lower()
    assert "never pick the newest" in lowered
    assert "run output" in lowered


def test_recipe_retry_limit():
    section = _recipe(_text())
    assert "2 retries" in section
    assert "3 attempts" in section


def test_recipe_makes_no_verification_claims():
    # The recipe is documentation only: it must not report observed outcomes or
    # verification (for example "a retry has succeeded") that nothing in the repo proves.
    lowered = _recipe(_text()).lower()
    for phrase in ("verified", "has succeeded", "tested on", "was tested", "confirmed on"):
        assert phrase not in lowered, phrase


def test_recipe_has_no_local_paths():
    section = _recipe(_text())
    assert not re.search(r"[A-Za-z]:\\Users|/home/|/Users/", section)
    assert LOCAL_PATH.search(section) is None


def test_recipe_prompt_path_is_a_placeholder_token():
    # The guard below swaps this token for absolute paths; it must be present in the real section.
    assert PROMPT_TOKEN in _recipe(_text())


@pytest.mark.parametrize("bad", [
    "/tmp/private/icon.md",
    "/var/folders/x/icon.md",
    "/home/user/icon.md",
    "/Users/user/icon.md",
    "~/art/icon.md",
    "C:\\private\\icon.md",
    "C:/private/icon.md",
    "C:\\Users\\user\\icon.md",
    "\\\\server\\share\\icon.md",
])
def test_local_path_guard_rejects_absolute_paths(bad):
    section = _recipe(_text()).replace(PROMPT_TOKEN, bad)
    assert PROMPT_TOKEN not in section
    assert LOCAL_PATH.search(section), bad


def test_local_path_guard_ignores_urls_and_relative_paths():
    sample = "see https://www.complete.tech/a and art/prompts/ORG/REPO/icon.md and run.jsonl"
    assert LOCAL_PATH.search(sample) is None


