"""E4.2.1: `readme --write` refuses generated or managed READMEs. Fixtures are synthetic inline text."""
import json
from types import SimpleNamespace

import pytest

from conftest import FIX, ROOT, run_cli
from ctshowcase import generated, readme

META = FIX / "CompleteTech-LLC__LoL_OBS_Overlay.json"
OTHER_OWNER_META = FIX / "Jev-Engineering__TypeCheck.json"
GENERATED_HEADER = "# Thing\n\n<!-- Generated by build-tool. DO NOT EDIT. -->\n\nBody text here.\n"


# -- detect ----------------------------------------------------------------------------------------------------------
@pytest.mark.parametrize("text, want", [
    ("---\ndescription: autogenerated reference\n---\n# Doc\n", "front-matter"),
    ("---\ngenerated: true\n---\n# Doc\n", "front-matter"),
    ("---\nauto_generated: yes\n---\n# Doc\n", "front-matter"),
    ("---\ngenerated: false\n---\n# Doc\n", None),
    ("---\ngenerated: true\n# Doc without a closing rule\n", None),
    ("# Doc\n<!-- Generated by build-tool -->\n", "header"),
    ("# Doc\n<!-- This file is automatically generated -->\n", "header"),
    ("# Doc\n<!-- @generated -->\n", "header"),
    ("# Doc\n<!--\n  please do not manually edit this file\n-->\n", "header"),
    ("# Doc\n<!-- don't edit -->\n", "header"),
    ("﻿# Doc\r\n<!-- DO NOT EDIT -->\r\n", "header"),
    ("# Doc\n<!-- showcase:template-body -->\n<!-- showcase:banner:start -->\n", None),
    ("# Doc\n<!-- showcase:footer: generated by the footer generator -->\n", None),
    ("# Doc\n\nThis page was generated by hand.\n", None),
    ("# Doc\n```\n<!-- Generated by build-tool -->\n```\n", None),
    ("# Doc\n~~~\n<!-- DO NOT EDIT -->\n~~~\n", None),
    # a shorter fence inside a longer one does not close it, so the header after the real close is still seen
    ("# Doc\n````markdown\n```\n````\n<!-- Generated by build-tool -->\n", "header"),
    # an inline code example is visible text, not a header comment
    ("# Doc\nUse `<!-- Generated by build-tool -->` as a comment.\n", None),
    ("# Doc\n<!-- Generated by `build-tool` -->\n", "header"),
    ("# Doc\n<!-- Generated by build-tool\n", None),
    ("# Doc\n" + "\n" * 25 + "<!-- Generated by build-tool -->\n", None),
    ("", None),
])
def test_detect(text, want):
    assert generated.detect(text) == want


def test_detect_never_returns_file_text():
    assert generated.detect(GENERATED_HEADER) in ("header", "front-matter")
    assert generated.detect(GENERATED_HEADER) not in GENERATED_HEADER


# -- managed_reason: the config key and the default -----------------------------------------------------------------
def ctx_with(**override):
    return SimpleNamespace(override=override)


def test_managed_reason_default_follows_detection():
    assert generated.managed_reason(ctx_with(), GENERATED_HEADER) == "header"
    assert generated.managed_reason(ctx_with(), "# Plain\n") is None


def test_managed_reason_authored_opts_out():
    assert generated.managed_reason(ctx_with(readme="authored"), GENERATED_HEADER) is None


def test_managed_reason_managed_refuses_without_detection():
    assert generated.managed_reason(ctx_with(readme="managed"), "# Plain\n") == "config"


# -- CLI: refusal on --write, dry run still shows the diff ----------------------------------------------------------
def write_readme(tmp_path, text):
    (tmp_path / "README.md").write_text(text, encoding="utf-8")
    return tmp_path / "README.md"


def test_cli_write_refuses_generated_readme(tmp_path):
    path = write_readme(tmp_path, GENERATED_HEADER)
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--write")
    assert p.returncode == 4, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert out["result"] == "needs-input" and out["written"] is False and out["managed"] == "header"
    assert "needs-input:readme-managed" in out["logs"] and "readme-managed:header" in out["logs"]
    assert path.read_text(encoding="utf-8") == GENERATED_HEADER


@pytest.mark.parametrize("mode", ["auto", "scaffold", "upgrade", "header"])
def test_cli_write_refuses_every_mode(tmp_path, mode):
    path = write_readme(tmp_path, GENERATED_HEADER)
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--mode", mode, "--write")
    assert p.returncode == 4 and json.loads(p.stdout)["written"] is False
    assert path.read_text(encoding="utf-8") == GENERATED_HEADER


def test_cli_write_refuses_bootstrap(tmp_path):
    path = write_readme(tmp_path, "---\ngenerated: true\n---\n# Doc\n")
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--bootstrap", "--write")
    assert p.returncode == 4 and json.loads(p.stdout)["managed"] == "front-matter"
    assert path.read_text(encoding="utf-8") == "---\ngenerated: true\n---\n# Doc\n"


def test_cli_write_refusal_leaves_badge_files_and_contributing_alone(tmp_path):
    # A pristine template body (bootstrap would fill it) under a generated header. Without the managed guard,
    # --bootstrap --write --badges local would write the badge SVGs and rewrite CONTRIBUTING.md's template links,
    # so each assertion below fails if the guard moves below those writes or is removed.
    template_contributing = "# Contributing\n\nSee https://github.com/CompleteTech-LLC/.github/blob/main/CONTRIBUTING.md\n"
    text = ("# Thing\n\n<!-- Generated by build-tool. DO NOT EDIT. -->\n\n"
            + readme.pristine_block("## About\n\nTemplate body.") + "\n")
    path = write_readme(tmp_path, text)
    # a repository owned by another org: the template .github links would be rewritten to that org
    contributing = tmp_path / "CONTRIBUTING.md"
    contributing.write_text(template_contributing, encoding="utf-8")
    p = run_cli("--meta", OTHER_OWNER_META, "--repo-dir", tmp_path, "readme", "--bootstrap", "--badges", "local", "--write")
    assert p.returncode == 4, p.stdout + p.stderr
    assert json.loads(p.stdout)["managed"] == "header"
    assert path.read_text(encoding="utf-8") == text
    assert contributing.read_text(encoding="utf-8") == template_contributing
    assert not any(tmp_path.rglob("*.svg"))


def test_cli_dry_run_still_prints_diff_for_generated_readme(tmp_path):
    path = write_readme(tmp_path, GENERATED_HEADER)
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme")
    assert p.returncode == 0, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert out["diff"].startswith("--- a/README.md") and out["managed"] == "header"
    assert path.read_text(encoding="utf-8") == GENERATED_HEADER


def test_cli_plain_readme_is_not_refused(tmp_path):
    write_readme(tmp_path, "# Plain\n\nHand written.\n")
    p = run_cli("--meta", META, "--repo-dir", tmp_path, "readme", "--write")
    assert p.returncode == 0 and "managed" not in json.loads(p.stdout)


# -- action.yml: the readme step treats a managed refusal as a skip, not a failure -----------------------------------
def test_action_readme_step_skips_managed_refusal():
    text = (ROOT / "action.yml").read_text(encoding="utf-8")
    assert 'if [ "$rc" -eq 4 ] && grep -q \'needs-input:readme-managed\' "$RUNNER_TEMP/readme.json"' in text
    assert "README skipped: it is generated or marked readme: managed" in text
    body = text[text.index("readme_step() {"):]
    body = body[:body.index("bootstrapped=false")]
    assert body.index("needs-input:readme-managed") < body.index('return "$rc"')


