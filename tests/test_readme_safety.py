"""Authored content controls for README refreshes and repository-owned generators."""
import pytest

from ctshowcase import readme


def test_default_refreshes_only_marked_tagline(make_ctx):
    old_ctx = make_ctx(description="Run the previous workflow for teams.")
    before = readme.scaffold(old_ctx) + "\nA separately authored sentence.\n"
    ctx = make_ctx(description="Run the current workflow for teams.")
    after, removed = readme.upgrade(ctx, before)
    assert "**Run the current workflow for teams.**" in after
    assert "Run the previous workflow" not in after
    assert "A separately authored sentence." in after
    assert readme.preservation(before, after, removed) == []


def test_authored_extra_in_tagline_still_protected(make_ctx):
    before = readme.scaffold(make_ctx(description="Run the previous workflow for teams."))
    before = before.replace("**Run the previous workflow for teams.**", "**Run the previous workflow for teams.**\nAn authored explanation.")
    after, removed = readme.upgrade(make_ctx(description="Run the current workflow for teams."), before)
    assert any("An authored explanation" in p for p in readme.preservation(before, after, removed))


def test_marker_example_and_unmarked_tagline_not_exempted():
    example = "```html\n" + readme.wrap("tagline", "**Author statement.**") + "\n```\n"
    assert any("Author statement" in p for p in readme.preservation(example, "```html\n```\n", []))
    assert readme.preservation("**Author statement.**\n", "", [])


@pytest.mark.parametrize("notice", ["<!-- Generated by scripts/docs.py -->", "<!-- DO NOT EDIT -->", "---\ngenerated_by: docs\nnotice: DO NOT EDIT\n---"])
def test_managed_notices_in_intro(make_ctx, notice):
    assert readme.managed_reason(make_ctx(), notice + "\n# A project\n")


def test_managed_config_and_later_examples(make_ctx):
    ctx = make_ctx()
    ctx.override = {"readme": {"managed": True}}
    assert readme.managed_reason(ctx, "# Project\n")
    assert readme.managed_reason(make_ctx(), "\n" * 20 + "Generated by example") is None


def test_no_regroup_preserves_outside_marker_bytes(make_ctx):
    ctx = make_ctx(description="Run the new workflow for teams.")
    before = "# My Title\n\n## Unusual   heading\n\n  Exact text.\n\n" + readme.wrap("tagline", "**Old.**") + "\n\n\n## Last\nbody\n"
    after = readme.header_only(ctx, before, preserve_structure=True)
    assert after == before.replace("**Old.**", "**Run the new workflow for teams.**")
    assert readme.heading_moves(before, after) == []


def test_heading_summary_excludes_added_and_code_headings():
    before = "# Title\n\n## Installation\nbody\n\n## Custom\n\n```text\n## Fake\n```\n"
    after = "# Title\n\n## Install\nbody\n\n## Notes\n\n### Custom\n\n```text\n## Fake\n```\n\n## Added\n"
    assert readme.heading_moves(before, after) == [
        {"heading": "Installation", "from": 2, "to": 2, "new_heading": "Install"},
        {"heading": "Custom", "from": 2, "to": 3, "new_heading": "Custom"},
    ]


def test_supplied_section_facts_fill_missing_sections_only(make_ctx):
    ctx = make_ctx()
    ctx.det["variant"] = "C"
    ctx.override = {"readme": {"sections": {"Usage": "Run `demo --help`.", "Install": "Use the package installer."}}}
    scaffold = readme.scaffold(ctx)
    assert "## Usage\n\nRun `demo --help`." in scaffold
    before = "# Project\n\n## Usage\n\nKeep my instructions.\n"
    after, removed = readme.upgrade(ctx, before)
    assert "Keep my instructions." in after
    assert "Run `demo --help`." not in after
    assert readme.preservation(before, after, removed) == []
