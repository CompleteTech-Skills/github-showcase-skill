@pytest.mark.parametrize("name", ["banner", "nav", "badges", "checklist", "footer"])
@pytest.mark.parametrize("args", [("--mode", "header"), ("--no-regroup",), ()])
def test_uncertain_marker_content_refuses_before_any_write(tmp_path, name, args):
    before = f"# Project\n\n<!-- showcase:{name}:start -->\n## Authored heading\nUnique authored content.\n<!-- showcase:{name}:end -->\n\n## Usage\nBody.\n"
    record = tmp_path / "records.jsonl"
    checkout, result = invoke(tmp_path, before, "--write", "--badges", "local", "--records", record, *args)
    if result.returncode == 0:
        assert "## Authored heading\nUnique authored content." in (checkout / "README.md").read_text(encoding="utf-8")
    else:
        assert result.returncode in (1, 4), result.stdout
        assert (checkout / "README.md").read_bytes() == before.encode()
        assert not (checkout / "docs").exists()
        assert not record.exists()


def test_duplicate_heading_summary_is_explicitly_ambiguous(tmp_path):
    before = "# Project\n\n## Custom\nFirst.\n\n### Custom\nSecond.\n"
    _, result = invoke(tmp_path, before)
    assert result.returncode == 0, result.stdout
    moves = json.loads(result.stdout)["heading_moves"]
    assert any(m.get("ambiguous") and m["heading"] == "Custom" for m in moves)
