"""The public command must enforce README ownership before any output writes."""
import json

import pytest

from conftest import meta_dict, run_cli


def invoke(tmp_path, text, *args, config=None):
    checkout = tmp_path / "repo"
    checkout.mkdir(exist_ok=True)
    (checkout / "README.md").write_bytes(text.encode())
    if config:
        (checkout / ".github").mkdir(exist_ok=True)
        (checkout / ".github/showcase.yml").write_text(config, encoding="utf-8")
    meta = tmp_path / "meta.json"
    meta.write_text(json.dumps(meta_dict(description="Run the updated workflow.")), encoding="utf-8")
    result = run_cli("--meta", meta, "--repo-dir", checkout, "readme", *args)
    return checkout, result


@pytest.mark.parametrize("config,notice", [(None, "<!-- DO NOT EDIT: Generated by build.py -->\n"),
                                           ("readme:\n  managed: true\n", "")])
def test_managed_write_refuses_before_side_effects(tmp_path, config, notice):
    original = notice + "# Project\n\nOriginal authored text.\n"
    record = tmp_path / "records.jsonl"
    checkout, result = invoke(tmp_path, original, "--write", "--badges", "local", "--records", record, config=config)
    assert result.returncode == 4, result.stderr
    payload = json.loads(result.stdout)
    assert payload["written"] is False
    assert "needs-input:readme-managed" in payload["logs"]
    assert payload["proposed_header"]
    assert (checkout / "README.md").read_bytes() == original.encode()
    assert not (checkout / "docs").exists()
    assert not record.exists()


def test_managed_dry_run_returns_header_without_writing(tmp_path):
    checkout, result = invoke(tmp_path, "<!-- Generated by docs -->\n# Project\n")
    assert result.returncode == 0, result.stderr
    payload = json.loads(result.stdout)
    assert payload["result"] == "needs-input"
    assert "showcase:" in payload["proposed_header"]
    assert not (checkout / "docs").exists()


def test_no_regroup_keeps_outside_bytes_and_refreshes_only_tagline(tmp_path):
    before = "# My Title\r\n\r\n## Unusual  heading\r\n Exact text.\r\n\r\n<!-- showcase:tagline:start -->\r\n**Old.**\r\n<!-- showcase:tagline:end -->\r\n\r\n## Last\r\nTail.\r\n"
    checkout, result = invoke(tmp_path, before, "--write", "--no-regroup")
    assert result.returncode == 0, result.stderr
    after = (checkout / "README.md").read_bytes()
    assert after.startswith(b"# My Title\r\n\r\n## Unusual  heading\r\n Exact text.\r\n\r\n")
    assert after.endswith(b"\r\n\r\n## Last\r\nTail.\r\n")
    assert b"Run the updated workflow." in after
    assert json.loads(result.stdout)["heading_moves"] == []


@pytest.mark.parametrize("args", [("--bootstrap",), ("--mode", "scaffold")])
def test_no_regroup_rejects_conflicting_modes(tmp_path, args):
    checkout, result = invoke(tmp_path, "# Original\n", "--write", "--no-regroup", *args)
    assert result.returncode == 2
    assert (checkout / "README.md").read_text(encoding="utf-8") == "# Original\n"


def test_section_facts_are_loaded_from_configuration(tmp_path):
    checkout, result = invoke(tmp_path, "", "--variant", "C", "--write",
                              config="readme:\n  sections:\n    Usage: 'Run `northwind --help`.'\n")
    assert result.returncode == 0, result.stderr
    assert "Run `northwind --help`." in (checkout / "README.md").read_text(encoding="utf-8")


@pytest.mark.parametrize("args", [("--mode", "header"), ("--no-regroup",), ()])
def test_authored_tagline_lines_survive_refresh(tmp_path, args):
    before = "# Project\n\n<!-- showcase:tagline:start -->\n**Old.**\nAuthored line.\n<!-- showcase:tagline:end -->\n\n## Usage\nBody.\n"
    record = tmp_path / "records.jsonl"
    checkout, result = invoke(tmp_path, before, "--write", "--badges", "local", "--records", record, *args)
    assert result.returncode == 0, result.stdout
    after = (checkout / "README.md").read_text(encoding="utf-8")
    assert "Authored line." in after
    assert "Run the updated workflow." in after


@pytest.mark.parametrize("newline", ["\n", "\r\n", "\r"])
def test_tagline_refresh_preserves_endings_and_bom(tmp_path, newline):
    before = "\ufeff" + newline.join(["# Project", "", "<!-- showcase:tagline:start -->",
                                      "**Old *marked* description.**", "<!-- showcase:tagline:end -->", "", "## Usage", "Body.", ""])
    checkout, result = invoke(tmp_path, before, "--write", "--no-regroup")
    assert result.returncode == 0, result.stdout
    after = (checkout / "README.md").read_bytes()
    assert after == before.replace("Old *marked* description.", "Run the updated workflow.").encode()
    result = run_cli("--meta", tmp_path / "meta.json", "--repo-dir", checkout, "readme", "--write", "--no-regroup")
    assert result.returncode == 0
    assert (checkout / "README.md").read_bytes() == after


def test_managed_frontmatter_and_prose_are_distinct(tmp_path):
    checkout, result = invoke(tmp_path, "---\ngenerated_by: build.py\n---\n# Project\n", "--write")
    assert result.returncode == 4
    checkout, result = invoke(tmp_path, "# Project\n\nThe report is generated by users.\n", "--write")
    assert result.returncode == 0, result.stdout


