"""Actual CLI upgrades preserve an authored U+FEFF after the encoding BOM (#159)."""
import json
import re

import pytest

from conftest import run_cli
from test_personal_hero_order import LEGACY_HERO, applicable_intro as applicable_intro, fixture_repo, snapshot
from test_personal_hero_url_authority import offline_cli as offline_cli


BOM = b"\xef\xbb\xbf"
HERO = re.compile(br"<!-- showcase:banner:start -->.*?<!-- showcase:banner:end -->", re.DOTALL)


@pytest.mark.parametrize("variant", ["G", "H"])
@pytest.mark.parametrize("bom_count", [1, 2], ids=["encoding-bom-control", "encoding-and-authored-bom"])
def test_callout_upgrade_keeps_bom_prefix_authored_suffix_and_crlf(
        tmp_path, applicable_intro, variant, bom_count):
    prefix = BOM * bom_count
    suffix = (b"\r\n\r\n# Synthetic profile\r\n\r\n"
              b"Authored  double spaces.  \r\n\r\n\tIndented authored note.\r\n\r\n")
    source = prefix + LEGACY_HERO.replace(b"\n", b"\r\n") + suffix
    meta = fixture_repo(tmp_path, source, applicable_intro)
    # Use the public variant selector while keeping the synthetic existing files
    # and the applicable intro generated by the shared CLI fixture.
    def upgrade():
        return run_cli("--format", "json", "--meta", meta, "--repo-dir", tmp_path,
                       "readme", "--mode", "upgrade", "--variant", variant, "--badges", "local",
                       "--records", tmp_path / "records.jsonl", "--write")

    result = upgrade()

    assert result.returncode == 0, result.stdout + result.stderr
    updated = (tmp_path / "README.md").read_bytes()
    block, = HERO.finditer(updated)
    assert updated[:block.start()] == prefix, "Keep the encoding BOM and every authored U+FEFF byte"
    assert updated.count(BOM) == bom_count
    assert b'src="assets/intro.svg"' in block.group()
    assert b"docs/images/banner.png" not in updated
    assert updated[block.end():].startswith(suffix), "Authored suffix bytes must stay attached"
    assert updated.count(suffix) == 1
    assert b"\n" not in updated.replace(b"\r\n", b"")
    assert b"\r" not in updated.replace(b"\r\n", b"")
    assert (tmp_path / "assets/intro.svg").read_bytes() == applicable_intro
    before_retry = snapshot(tmp_path)

    retry = upgrade()

    assert retry.returncode == 0, retry.stdout + retry.stderr
    report = json.loads(retry.stdout)
    assert report["result"] == "unchanged" and report["written"] is False, report
    assert snapshot(tmp_path) == before_retry, "Repeating the migration must be byte-idempotent"


@pytest.mark.parametrize("variant", ["J", "G", "H"])
@pytest.mark.parametrize("bom_count", [1, 2], ids=["encoding-bom-control", "encoding-and-authored-bom"])
def test_header_refresh_keeps_bom_prefix_and_immediately_adjacent_authored_suffix(
        tmp_path, applicable_intro, variant, bom_count):
    prefix = BOM * bom_count
    suffix = (b"QAuthored suffix  starts immediately after the marker.  \r\n"
              b"\r\n# Synthetic profile\r\n\r\nKeep  these authored notes.\r\n")
    source = prefix + LEGACY_HERO.replace(b"\n", b"\r\n") + suffix
    meta = fixture_repo(tmp_path, source, applicable_intro)

    def refresh():
        return run_cli("--format", "json", "--meta", meta, "--repo-dir", tmp_path,
                       "readme", "--mode", "header", "--variant", variant, "--badges", "local",
                       "--records", tmp_path / "records.jsonl", "--write")

    result = refresh()

    assert result.returncode == 0, result.stdout + result.stderr
    updated = (tmp_path / "README.md").read_bytes()
    block, = HERO.finditer(updated)
    assert updated[:block.start()] == prefix, "The BOM prefix must meet the valid marker without extra bytes"
    assert updated.count(BOM) == bom_count
    assert updated.count(b"<!-- showcase:banner:start -->") == 1
    assert updated.count(b"<!-- showcase:banner:end -->") == 1
    assert b'src="assets/intro.svg"' in block.group()
    assert b"docs/images/banner.png" not in updated
    assert updated[block.end():] == suffix, "Keep the complete adjacent suffix, including its leading Q"
    assert b"\n" not in updated.replace(b"\r\n", b"")
    assert b"\r" not in updated.replace(b"\r\n", b"")
    assert (tmp_path / "assets/intro.svg").read_bytes() == applicable_intro
    before_retry = snapshot(tmp_path)

    retry = refresh()

    assert retry.returncode == 0, retry.stdout + retry.stderr
    report = json.loads(retry.stdout)
    assert report["result"] == "unchanged" and report["written"] is False, report
    assert snapshot(tmp_path) == before_retry, "Repeating the refresh must be byte-idempotent"
